export function buildDamLevel(o, level = 'master') {
  const c = cfg[level];
  if (!c) throw Error('Unknown Banqiao tier ' + level);
  for (const wing of controls.wings) earthwork(o, c, wing);
  crossing(o, c);
  intake(o, c);
  stair(o, c);
  pavingSeams(o, c);
  crestLights(o, c);
}
