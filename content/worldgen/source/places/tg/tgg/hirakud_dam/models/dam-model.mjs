const lerp = (a, b, f) => a + (b - a) * f;
function box(o, c, a, b, z, w, y, h, s) {
  const A = [a, h, z],
    B = [b, h, z],
    D = [a, h, w],
    E = [b, h, w],
    p = [a, y, z],
    r = [b, y, z],
    u = [a, y, w],
    v = [b, y, w];
  for (const [ps, n] of [
    [
      [A, B, E, D],
      [0, 1, 0],
    ],
    [
      [p, r, B, A],
      [0, 0, -1],
    ],
    [
      [u, v, E, D],
      [0, 0, 1],
    ],
    [
      [p, u, D, A],
      [-1, 0, 0],
    ],
    [
      [r, v, E, B],
      [1, 0, 0],
    ],
  ])
    q(o, c, ps, s, n);
  if (c.near) q(o, c, [p, u, v, r], s, [0, -1, 0]);
}

function embankment(o, c, stations) {
  const slopeEnd = (station) =>
    station.x >= plant.cut[0] && station.x <= plant.cut[1]
      ? [station.x, plant.grade + 0.4, 21]
      : [station.x, station.down, station.z + station.w];
  for (let i = 1; i < stations.length; i++) {
    const a = stations[i - 1],
      b = stations[i],
      p = (q, z, y) => [q.x, q[y], q.z + z];
    q(
      o,
      c,
      [p(a, -35, 'up'), p(b, -35, 'up'), p(b, -5.5, 'y'), p(a, -5.5, 'y')],
      'wall',
      [0, 1, -1],
    );
    q(o, c, [p(a, -5.5, 'y'), p(b, -5.5, 'y'), p(b, 5.5, 'y'), p(a, 5.5, 'y')], 'road', [0, 1, 0]);
    q(o, c, [p(a, 5.5, 'y'), p(b, 5.5, 'y'), slopeEnd(b), slopeEnd(a)], 'earth', [0, 1, 1]);
    if (c.detail)
      for (const z of [-5.3, 5.3])
        rod(o, c, [a.x, a.y + 0.48, a.z + z], [b.x, b.y + 0.48, b.z + z], 0.16, 0.17, 'trim');
    if (c.fine)
      for (let j = 0; j < Math.ceil((b.x - a.x) / 34); j++) {
        const f = j / Math.ceil((b.x - a.x) / 34),
          x = lerp(a.x, b.x, f),
          y = lerp(a.y, b.y, f),
          z = lerp(a.z, b.z, f) + 4.9;
        rod(o, c, [x, y, z], [x, y + 4.25, z], 0.14, 0.14);
        rod(o, c, [x, y + 4.25, z], [x, y + 4.55, z - 1.22], 0.12, 0.12);
      }
  }
  for (const [station, side] of [
    [stations[0], -1],
    [stations.at(-1), 1],
  ]) {
    const crest = [station.x, station.y, station.z + 5.5],
      toe = slopeEnd(station);
    q(o, c, [crest, toe, [toe[0], foundation, toe[2]], [crest[0], foundation, crest[2]]], 'wall', [
      side,
      0,
      0,
    ]);
  }
}

