function pipeFrame(ps, t) {
  const p = bezier(ps, t),
    a = bezier(ps, Math.max(0, t - 0.001)),
    b = bezier(ps, Math.min(1, t + 0.001)),
    v = sub(b, a),
    L = Math.hypot(...v),
    U = v.map((v) => v / L),
    crossed = cross(U, [0, 1, 0]),
    K = Math.hypot(...crossed),
    V = crossed.map((v) => v / K),
    W = cross(U, V);
  return { p, U, V, W };
}
function pipeRing(ps, t, r, n, offset = 0) {
  const { p, U, V, W } = pipeFrame(ps, t);
  return Array.from({ length: n }, (_, i) => {
    const a = (i / n) * Math.PI * 2;
    return p.map((v, k) => v + U[k] * offset + r * (Math.cos(a) * V[k] + Math.sin(a) * W[k]));
  });
}
function pipe(o, c, pipe) {
  const n = c.round,
    ps = pipe.path;
  for (let j = 0; j < c.path; j++) {
    const a = pipeRing(ps, j / c.path, pipe.radius, n),
      b = pipeRing(ps, (j + 1) / c.path, pipe.radius, n),
      f = pipeFrame(ps, (j + 0.5) / c.path);
    for (let i = 0; i < n; i++) {
      const N = mix(a[i], b[i], 0.5).map((v, k) => v - f.p[k]);
      Q(o, c, [a[i], b[i], b[(i + 1) % n], a[(i + 1) % n]], 'metal', C.metal, N);
    }
  }
  // Visible collars are thin solid bands around each individual pipe,not flat painted lines.
  if (c.fine) {
    const length = Array.from({ length: 48 }, (_, i) =>
      Math.hypot(...sub(bezier(ps, (i + 1) / 48), bezier(ps, i / 48))),
    ).reduce((s, v) => s + v, 0);
    for (let d = c.collar; d < length - 4; d += c.collar) {
      const t = d / length,
        a = pipeRing(ps, t, pipe.radius + 0.22, n, -0.35),
        b = pipeRing(ps, t, pipe.radius + 0.22, n, 0.35);
      for (let i = 0; i < n; i++)
        Q(o, c, [a[i], b[i], b[(i + 1) % n], a[(i + 1) % n]], 'metal', C.metal);
      if (c.near) {
        const p = bezier(ps, t);
        box(
          o,
          c,
          p[0] - 1.5,
          p[0] + 1.5,
          p[1] - pipe.radius - 5,
          p[1] - pipe.radius + 0.15,
          p[2] - 1.5,
          p[2] + 1.5,
          'base',
        );
      }
    }
  }
}
function industrial(o, c, poly, floor, height, main) {
  panel(o, c, poly, floor + height + 0.5, 'roof');
  slab(o, c, poly[0], floor - 5, floor, 'base');
  ringEdges(poly, (e) => {
    const holes = [],
      long = e.L > 100;
    if (c.detail) {
      const count = long ? 8 : Math.max(1, Math.floor(e.L / 15));
      for (let i = 0; i < count; i++) {
        const u = ((i + 0.5) * e.L) / count;
        holes.push({
          ring: rect(u, floor + height * 0.58, (e.L / count) * 0.63, height * 0.24),
          kind: 'glass',
          depth: 0.35,
        });
        if (long && main && e.N[0] > 0.4)
          holes.push({
            ring: rect(u, floor + 1, (e.L / count) * 0.5, height * 0.4),
            kind: 'opening',
          });
      }
    }
    wall(o, c, e.p, e.L, floor, floor + height, holes, 'wall');
    if (c.detail) {
      band(o, c, e, floor + height - 0.3, 0.45, 'base', 0.15);
      band(o, c, e, floor + 0.3, 0.5, 'base', 0.15);
    }
    if (c.fine && long)
      for (let i = 0; i <= 8; i++) {
        const u = (i * e.L) / 8;
        beam(
          adapter(o, c),
          'base',
          e.p([u, floor, 0.15]),
          e.p([u, floor + height, 0.15]),
          0.5,
          0.6,
          C.base,
        );
        if (c.near && i < 8)
          beam(
            adapter(o, c),
            'dark',
            e.p([u + e.L / 16, floor + height * 0.58, -0.28]),
            e.p([u + e.L / 16, floor + height * 0.82, -0.28]),
            0.1,
            0.12,
            C.dark,
          );
      }
  });
  if (c.fine && main) {
    const r = openRing(poly[0]),
      a = r[0],
      b = r[1],
      L = Math.hypot(b[0] - a[0], b[1] - a[1]),
      U = [(b[0] - a[0]) / L, (b[1] - a[1]) / L];
    for (let j = 0; j < 8; j++) {
      const t = (j + 0.5) / 8,
        x = a[0] + (b[0] - a[0]) * t,
        z = a[1] + (b[1] - a[1]) * t;
      box(o, c, x - 2, x + 2, floor + height + 0.5, floor + height + 2.8, z - 2, z + 2, 'base');
      if (c.master)
        for (let q = -1; q <= 1; q++)
          beam(
            adapter(o, c),
            'dark',
            [x + q * 0.5, floor + height + 3, z - 1.5],
            [x + q * 0.5, floor + height + 3, z + 1.5],
            0.12,
            0.12,
            C.dark,
          );
    }
  }
}
function intake(o, c) {
  const a = [-821, -140],
    b = [-718, 112],
    poly = [
      [a[0] - 7, a[1]],
      [a[0] + 7, a[1]],
      [b[0] + 7, b[1]],
      [b[0] - 7, b[1]],
    ];
  slab(o, c, poly, -24, 13, 'wall');
  if (c.detail) beam(adapter(o, c), 'paving', pt(a, 13.3), pt(b, 13.3), 10, 0.6, C.paving);
  if (c.fine) {
    const L = Math.hypot(b[0] - a[0], b[1] - a[1]);
    for (let u = 0; u < L; u += c.post) {
      const p = mix(a, b, u / L);
      beam(adapter(o, c), 'dark', pt(p, 13), pt(p, 14.3), 0.13, 0.13, C.dark);
    }
    beam(adapter(o, c), 'dark', pt(a, 14.2), pt(b, 14.2), 0.15, 0.15, C.dark);
  }
}
function spillProfile(t) {
  return -4 - 138 * (t * t * (3 - 2 * t));
}
// A triangular far rib retains the full chute profile while discarding hidden box faces.
function farSpillRib(o, c, a, b, width, height, cap) {
  const dx = b[0] - a[0],
    dz = b[2] - a[2],
    L = Math.hypot(dx, dz),
    N = [dz / L, 0, -dx / L],
    ring = (p) => [
      [p[0] - (N[0] * width) / 2, p[1] - height / 2, p[2] - (N[2] * width) / 2],
      [p[0] + (N[0] * width) / 2, p[1] - height / 2, p[2] + (N[2] * width) / 2],
      [p[0], p[1] + height / 2, p[2]],
    ],
    A = ring(a),
    B = ring(b),
    center = a.map((v, i) => (v + b[i]) / 2);
  for (let i = 0; i < 3; i++) {
    const j = (i + 1) % 3,
      out = [0, 1, 2].map((k) => (A[i][k] + A[j][k] + B[i][k] + B[j][k]) / 4 - center[k]);
    Q(o, c, [A[i], B[i], B[j], A[j]], 'wall', C.wall, out);
  }
  if (cap) T(o, c, B, 'wall', C.wall, sub(b, a));
}
function spillway(o, c) {
  const s = controls.spillway,
    n = c === cfg.skyline ? 4 : c.master ? 48 : c.near ? 24 : 12,
    U = sub(s.start[1], s.start[0]),
    L = Math.hypot(...U),
    step = c === cfg.skyline ? 3 : 6,
    point = (u, t, y = 0) => {
      const a = mix(s.start[0], s.start[1], u),
        b = mix(s.end[0], s.end[1], u),
        p = mix(a, b, t);
      return [p[0], spillProfile(t) + y, p[1]];
    };
  for (let j = 0; j < n; j++) {
    Q(
      o,
      c,
      [point(0, j / n), point(1, j / n), point(1, (j + 1) / n), point(0, (j + 1) / n)],
      'wall',
      C.wall,
      [0, 1, 0],
    );
    Q(
      o,
      c,
      [
        point(0, j / n, -2.5),
        point(1, j / n, -2.5),
        point(1, (j + 1) / n, -2.5),
        point(0, (j + 1) / n, -2.5),
      ],
      'base',
      C.base,
      [0, -1, 0],
    );
    for (const u of [0, 1])
      Q(
        o,
        c,
        [
          point(u, j / n),
          point(u, (j + 1) / n),
          point(u, (j + 1) / n, -2.5),
          point(u, j / n, -2.5),
        ],
        'wall',
        C.wall,
      );
  }
  for (let i = 0; i <= step; i++)
    for (let j = 0; j < n; j++) {
      const a = point(i / step, j / n),
        b = point(i / step, (j + 1) / n);
      if (c === cfg.skyline)
        farSpillRib(
          o,
          c,
          [a[0], a[1] + 2, a[2]],
          [b[0], b[1] + 2, b[2]],
          i === 0 || i === step ? 2.7 : 1.2,
          4,
          j === n - 1,
        );
      else
        beam(
          adapter(o, c),
          'wall',
          [a[0], a[1] + 2, a[2]],
          [b[0], b[1] + 2, b[2]],
          i === 0 || i === step ? 2.7 : 1.2,
          4,
          C.wall,
        );
    }
  for (let i = 0; i <= 6; i++) {
    const p = point(i / 6, 0);
    beam(adapter(o, c), 'wall', [p[0], -9, p[2]], [p[0], 26, p[2]], 3.2, 7, C.wall);
    if (c.detail)
      beam(adapter(o, c), 'dark', [p[0] - 3, 26, p[2]], [p[0] + 3, 26, p[2]], 0.6, 0.8, C.dark);
  }
  for (let i = 0; i < 6; i++) {
    const a = point((i + 0.075) / 6, 0, 8),
      b = point((i + 0.925) / 6, 0, 8);
    beam(adapter(o, c), 'dark', a, b, 1.2, 18, C.dark);
  }
  if (c.detail) {
    beam(adapter(o, c), 'dark', point(0, 0, 31), point(1, 0, 31), 0.5, 0.6, C.dark);
    beam(adapter(o, c), 'paving', point(0, 0, 19), point(1, 0, 19), 9, 0.6, C.paving);
  }
  // Open stilling basin:water stays native context rather than an opaque modeled floor.
  const A = s.end[0],
    B = s.end[1],
    D = [A[0] - 100, A[1] + 150],
    E = [B[0] - 100, B[1] + 150];
  for (const [a, b] of [
    [A, D],
    [B, E],
  ])
    beam(adapter(o, c), 'wall', pt(a, -138), pt(b, -138), 3, 12, C.wall);
  if (c.fine)
    for (let i = 1; i < 6; i++) {
      const p = mix(D, E, i / 6);
      box(o, c, p[0] - 2, p[0] + 2, -149, -141, p[1] - 2, p[1] + 2, 'base');
    }
}
export function buildDamLevel(o, level = 'master', mark = () => {}) {
  const c = cfg[level];
  if (!c) throw Error('Unknown Ataturk tier ' + level);
  barrier(o, c);
  pipeBank(o, c);
  mark('whole-curved-rock-fill-barrier-and-crest');
  controls.penstocks.forEach((p) => {
    pipe(o, c, p);
  });
  intake(o, c);
  mark('eight-exposed-penstocks-and-intake');
  for (const poly of controls.powerhouse)
    industrial(o, c, poly, controls.floor, controls.hallHeight, true);
  for (const poly of controls.controlHouse)
    industrial(o, c, poly, controls.floor, controls.controlHeight, false);
  mark('native-powerhouse-and-control-house');
  spillway(o, c);
  mark('six-gates-divided-spillway-open-stilling-basin');
}
export const buildDamSkyline = (o) => buildDamLevel(o, 'skyline');
