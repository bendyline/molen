// Clip the coarse embankment away from the photographed pipe construction bank.
// Each original triangle is convex; successive half-plane splits retain only exterior pieces.
function clipTerrainTriangle(o, c, points, s, col, N) {
  const ring = openRing(controls.pipeApron),
    area = ring.reduce((n, a, i) => {
      const b = ring[(i + 1) % ring.length];
      return n + a[0] * b[1] - a[1] * b[0];
    }, 0),
    sign = area > 0 ? 1 : -1;
  let inside = points;
  const outside = [];
  for (let i = 0; i < ring.length && inside.length; i++) {
    const a = ring[i],
      b = ring[(i + 1) % ring.length],
      side = (p) => sign * ((b[0] - a[0]) * (p[2] - a[1]) - (b[1] - a[1]) * (p[0] - a[0])),
      yes = [],
      no = [];
    for (let j = 0; j < inside.length; j++) {
      const P = inside[j],
        R = inside[(j + 1) % inside.length],
        dp = side(P),
        dr = side(R),
        ip = dp >= 0,
        ir = dr >= 0;
      (ip ? yes : no).push(P);
      if (ip !== ir) {
        const t = dp / (dp - dr),
          q = mix(P, R, t);
        yes.push(q);
        no.push(q);
      }
    }
    if (no.length >= 3) outside.push(no);
    inside = yes;
  }
  // These are real excavation faces of the owned construction bank,not open sky holes.
  if (inside.length >= 3)
    for (let j = 0; j < inside.length; j++) {
      const P = inside[j],
        R = inside[(j + 1) % inside.length];
      for (let k = 0; k < ring.length; k++) {
        const a = ring[k],
          b = ring[(k + 1) % ring.length],
          dx = b[0] - a[0],
          dz = b[1] - a[1],
          L = Math.hypot(dx, dz),
          distance = (p) => Math.abs(dx * (p[2] - a[1]) - dz * (p[0] - a[0])) / L;
        if (
          L &&
          distance(P) < 0.0001 &&
          distance(R) < 0.0001 &&
          Math.hypot(P[0] - R[0], P[2] - R[2]) > 0.0001
        ) {
          Q(o, c, [P, R, [R[0], -155, R[2]], [P[0], -155, P[2]]], 'stone', C.stone, [
            -dz * sign,
            0,
            dx * sign,
          ]);
          break;
        }
      }
    }
  for (const poly of outside)
    for (let j = 1; j < poly.length - 1; j++) T(o, c, [poly[0], poly[j], poly[j + 1]], s, col, N);
}
