export function buildStationLevel(o, level = 'master') {
  const c = cfg[level];
  if (!c) throw Error('Unknown Oslo tier ' + level);
  heritage(o, c);
  innerHallClosure(o, c);
  hall(o, c);
  for (const f of controls.canopies) canopy(o, c, f);
  if (c.detail)
    for (const id of [723, 724, 725, 726, 712, 713, 711, 443])
      for (const p of controls.groups[id]) {
        const h = controls.nativeFacts.find((f) => f.index === id).properties.height ?? 6;
        solid(o, c, p, 1.4, Math.max(2, h), 'glass');
        panel(o, c, p, Math.max(2, h) + 0.08, 'roof');
        if (c.near)
          ringEdges(p, (e) => {
            for (let u = 0; u < e.L; u += c.master ? 1.4 : 2.8)
              beam(
                adapter(o, c),
                'metal',
                e.p([u, 1.4, 0.03]),
                e.p([u, h, 0.03]),
                0.08,
                0.1,
                C.metal,
              );
          });
      }
}
export const buildStationSkyline = (o) => buildStationLevel(o, 'skyline');
