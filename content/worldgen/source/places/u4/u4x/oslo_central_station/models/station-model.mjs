function ringEdges(poly, fn) {
  for (let k = 0; k < poly.length; k++) {
    let r = openRing(poly[k]);
    const area = r.reduce((s, p, i) => {
      const q = r[(i + 1) % r.length];
      return s + p[0] * q[1] - p[1] * q[0];
    }, 0);
    if (area < 0) r = [...r].reverse();
    for (let j = 0; j < r.length; j++) {
      let e = edge(r, j);
      if (k) {
        const p = e.p;
        e = { ...e, N: e.N.map((v) => -v), p: ([u, y, d]) => p([u, y, -d]) };
      }
      fn(e, k);
    }
  }
}

const bounds = (p) => {
  const a = p.flat();
  return [
    Math.min(...a.map((p) => p[0])),
    Math.min(...a.map((p) => p[1])),
    Math.max(...a.map((p) => p[0])),
    Math.max(...a.map((p) => p[1])),
  ];
};
function pitched(o, c, poly, lo, hi, s = 'slate') {
  const b = bounds(poly),
    zAxis = b[3] - b[1] > b[2] - b[0],
    v = zAxis ? 0 : 1,
    min = zAxis ? b[0] : b[1],
    max = zAxis ? b[2] : b[3],
    h = ([x, z]) =>
      lo + (hi - lo) * (1 - Math.abs(((v === 0 ? x : z) - min) / (max - min) - 0.5) * 2),
    a = poly.map(openRing),
    flat = a.flat(),
    holes = a.slice(1).map((_, i) => a.slice(0, i + 1).reduce((n, r) => n + r.length, 0));
  const ridge = (min + max) / 2,
    side = [[], []];
  for (const r of a) {
    const aa = [],
      bb = [];
    for (let j = 0; j < r.length; j++) {
      const p = r[j],
        q = r[(j + 1) % r.length];
      if (p[v] <= ridge) aa.push(p);
      if (p[v] >= ridge) bb.push(p);
      if ((p[v] < ridge && q[v] > ridge) || (p[v] > ridge && q[v] < ridge)) {
        const t = (ridge - p[v]) / (q[v] - p[v]),
          m = p.map((x, i) => x + (q[i] - x) * t);
        aa.push(m);
        bb.push(m);
      }
    }
    if (aa.length > 2) side[0].push(aa);
    if (bb.length > 2) side[1].push(bb);
  }
  for (const rs of side) if (rs.length) panel(o, c, rs, h, s);
  ringEdges(poly, (e) => {
    Q(
      o,
      c,
      [
        [e.a[0], lo, e.a[1]],
        [e.b[0], lo, e.b[1]],
        [e.b[0], h(e.b), e.b[1]],
        [e.a[0], h(e.a), e.a[1]],
      ],
      s,
      C[s],
      e.N,
    );
  });
  if (c.fine) {
    const A = zAxis ? [ridge, hi, b[1]] : [b[0], hi, ridge],
      B = zAxis ? [ridge, hi, b[3]] : [b[2], hi, ridge];
    beam(adapter(o, c), 'metal', A, B, 0.12, 0.16, C.metal);
  }
}
