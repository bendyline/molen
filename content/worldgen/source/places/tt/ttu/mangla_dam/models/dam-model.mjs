function embankment(o, c) {
  const rows = stations.filter((_, i) => i % c.station === 0 || i === stations.length - 1);
  const sections = rows.map((q) => {
    const { crown, downY, upY, downWidth, upWidth, roadHalf } = q,
      e = roadHalf + 2.4;
    return (
      c === cfg.skyline
        ? [
            [upWidth, upY, 'rock'],
            [roadHalf, crown, 'rock'],
            [-roadHalf, crown, 'road'],
            [-downWidth, downY, 'rock'],
          ]
        : [
            [upWidth, upY, 'rock'],
            [lerp(upWidth, e, 0.47), lerp(upY, crown, 0.51), 'rock'],
            [e, crown - 0.23, 'rockLight'],
            [roadHalf, crown, 'gravel'],
            [-roadHalf, crown, 'road'],
            [-e, crown - 0.23, 'gravel'],
            [lerp(-e, -downWidth, 0.42), lerp(crown, downY, 0.48), 'rockLight'],
            [lerp(-e, -downWidth, 0.74), lerp(crown, downY, 0.81), 'rock'],
            [-downWidth, downY, 'rock'],
          ]
    ).map(([s, y, slot]) => ({ p: ridge(q, s, y), slot }));
  });
  for (let i = 1; i < sections.length; i++) {
    const a = sections[i - 1],
      b = sections[i],
      n = rows[i].normal;
    for (let j = 1; j < a.length; j++) {
      const { slot } = a[j];
      Q(o, c, [a[j - 1].p, b[j - 1].p, b[j].p, a[j].p], slot, C[slot], [0, 1, 0]);
    }
    for (const [j, side] of [
      [0, 1],
      [a.length - 1, -1],
    ]) {
      const p = a[j].p,
        q = b[j].p,
        drop = Math.max(foundation, Math.min(p[1], q[1]) - 13);
      Q(o, c, [p, q, [q[0], drop, q[2]], [p[0], drop, p[2]]], 'rock', C.rock, [
        side * n[0],
        0,
        side * n[1],
      ]);
    }
    if (c.near && Math.hypot(...rows[i].p) < 520) {
      const q = rows[i],
        prev = rows[i - 1],
        depth = q.roadHalf + 0.9;
      for (const side of [1, -1]) {
        const P = ridge(q, side * depth, q.crown + 1.02),
          A = ridge(prev, side * depth, prev.crown + 1.02);
        beam(adapter(o, c), 'rail', A, P, 0.12, 0.11, C.rail);
        const L = Math.hypot(P[0] - A[0], P[2] - A[2]);
        for (let k = 1, m = Math.max(1, Math.ceil(L / (c.master ? 5 : 10))); k <= m; k++) {
          const t = k / m,
            p = A.map((v, j) => lerp(v, P[j], t));
          beam(adapter(o, c), 'rail', [p[0], p[1] - 1, p[2]], p, 0.09, 0.09, C.rail);
        }
      }
    }
  }
}
function gateBox(o, c, a, b, v, w, low, high, slot) {
  const P = (u, z, y) => gatePoint(u, z, y),
    p = [P(a, v, low), P(b, v, low), P(b, w, low), P(a, w, low)],
    q = [P(a, v, high), P(b, v, high), P(b, w, high), P(a, w, high)];
  Q(o, c, q, slot, C[slot], [0, 1, 0]);
  if (c !== cfg.skyline) Q(o, c, p, slot, C[slot], [0, -1, 0]);
  for (const [i, n] of [
    [0, [0, 0, -1]],
    [1, [1, 0, 0]],
    [2, [0, 0, 1]],
    [3, [-1, 0, 0]],
  ]) {
    const j = (i + 1) % 4;
    Q(o, c, [p[i], p[j], q[j], q[i]], slot, C[slot], n);
  }
}
function mainSpillway(o, c) {
  const { rows, span, bays, crest, sill } = gate;
  for (let i = 1; i < rows.length; i++) {
    const [v, a, b, y] = rows[i - 1],
      [w, d, e, h] = rows[i];
    const lip = (z, j) => (z < 18 ? 22 : z < 50 ? 25 : z < 110 ? j + 21 : z < 250 ? j + 13 : j + 8);
    const top = lip(v, y),
      end = lip(w, h);
    Q(
      o,
      c,
      [gatePoint(a, v, y), gatePoint(b, v, y), gatePoint(e, w, h), gatePoint(d, w, h)],
      i < 7 ? 'chute' : 'base',
      C[i < 7 ? 'chute' : 'base'],
      [0, 1, 0],
    );
    for (const [p, q, side] of [
      [a, d, -1],
      [b, e, 1],
    ]) {
      const A = gatePoint(p, v, top),
        B = gatePoint(q, w, end);
      const P = gatePoint(p, v, y),
        R = gatePoint(q, w, h);
      const U = gatePoint(p + side * 4.6, v, top - 0.3),
        V = gatePoint(q + side * 4.6, w, end - 0.3);
      Q(o, c, [P, R, B, A], 'concrete', C.concrete, [-side, 0, 0]);
      Q(o, c, [A, B, V, U], 'base', C.base, [0, 1, 0]);
      const toeA = gatePoint(p + side * 13, v, y - 2),
        toeB = gatePoint(q + side * 13, w, h - 2);
      Q(o, c, [U, V, toeB, toeA], 'concrete', C.concrete, [side, 0, 0]);
      Q(
        o,
        c,
        [
          toeA,
          toeB,
          gatePoint(q + side * 13, w, foundation),
          gatePoint(p + side * 13, v, foundation),
        ],
        'base',
        C.base,
        [side, 0, 0],
      );
      if (c.detail && i < 8) {
        const a = gatePoint(p + side * 2.3, v, top - 0.03),
          b = gatePoint(q + side * 2.3, w, end - 0.03);
        beam(adapter(o, c), 'rail', a, b, 0.18, 0.18, C.rail);
      }
    }
  }
  const h = span / 2,
    width = span / bays;
  gateBox(o, c, -h - 4, h + 4, -10, 11, crest - 1.65, crest, 'road');
  gateBox(o, c, -h - 2, h + 2, -10, -2, sill - 5, sill, 'base');
  for (let i = 0; i <= bays; i++) {
    const u = -h + i * width;
    gateBox(o, c, u - 1.6, u + 1.6, -9, 14, sill - 5, crest, 'concrete');
    for (const side of [-1, 1]) {
      const p = u + side * 1.6,
        A = gatePoint(p, -12, crest - 0.8),
        B = gatePoint(p, -14, sill - 4),
        D = gatePoint(p, -32, sill - 4);
      T(o, c, [A, B, D], 'base', C.base, [side, 0, 0]);
    }
    Q(
      o,
      c,
      [
        gatePoint(u - 1.6, -12, crest - 0.8),
        gatePoint(u + 1.6, -12, crest - 0.8),
        gatePoint(u + 1.6, -32, sill - 4),
        gatePoint(u - 1.6, -32, sill - 4),
      ],
      'concrete',
      C.concrete,
      [0, 1, 0],
    );
    if (i === bays) continue;
    gateBox(o, c, u + 1.6, u + width - 1.6, 0, 2.6, sill + 3.4, crest - 2.4, 'steel');
    if (c.detail) {
      gateBox(o, c, u + 3.6, u + width - 3.6, -0.8, 6, crest, crest + 1.85, 'concrete');
      if (c.fine)
        for (const side of [4.4, width - 4.4]) {
          beam(
            adapter(o, c),
            'steel',
            gatePoint(u + side, 2.7, sill + 4.6),
            gatePoint(u + side, 2.7, crest + 0.65),
            0.16,
            0.26,
            C.steel,
          );
        }
    }
  }
  if (c.detail) {
    // Center access walk ends in a concrete inspection block above the stilling pool.
    gateBox(o, c, -2.2, 2.2, 292, 383, -76, -65.5, 'base');
    gateBox(o, c, -7.3, 7.3, 285, 300, -76, -63, 'concrete');
    for (const u of [-2, 2]) {
      beam(
        adapter(o, c),
        'rail',
        gatePoint(u, 303, -64.4),
        gatePoint(u, 380, -64.4),
        0.11,
        0.11,
        C.rail,
      );
      if (c.fine)
        for (let v = 304; v <= 378; v += 4.5)
          beam(
            adapter(o, c),
            'rail',
            gatePoint(u, v, -65.5),
            gatePoint(u, v, -64.4),
            0.09,
            0.09,
            C.rail,
          );
    }
  }
}

export const plantOutline = controls.plant.slice(0, -1);
function plantPoint(a, b, y) {
  const [p, q, r, s] = plantOutline;
  const f = p.map((v, i) => lerp(v, q[i], b)),
    g = s.map((v, i) => lerp(v, r[i], b));
  return v3(
    f.map((v, i) => lerp(v, g[i], a)),
    y,
  );
}
function plantBlock(o, c, a, b, u, v, low, high, slot) {
  const p = [
      plantPoint(a, u, low),
      plantPoint(b, u, low),
      plantPoint(b, v, low),
      plantPoint(a, v, low),
    ],
    q = p.map(([x, , z]) => [x, high, z]);
  Q(o, c, q, slot, C[slot], [0, 1, 0]);
  Q(o, c, p, slot, C[slot], [0, -1, 0]);
  for (let i = 0; i < 4; i++) {
    const j = (i + 1) % 4,
      n = [p[i][2] - p[j][2], 0, p[j][0] - p[i][0]];
    Q(o, c, [p[i], p[j], q[j], q[i]], slot, C[slot], n);
  }
}
function powerhouse(o, c) {
  plantBlock(o, c, 0, 1, 0, 1, foundation, -63, 'base');
  plantBlock(o, c, 0, 1, 0.06, 0.94, -63, -49, 'concrete');
  for (const [a, b] of [
    [0.035, 0.5],
    [0.5, 0.965],
  ]) {
    const P = (s, t) => plantPoint(s, t, t === 0.5 ? -45.7 : -49);
    Q(o, c, [P(0, a), P(1, a), P(1, b), P(0, b)], 'roof', C.roof, [0, 1, 0]);
  }
  for (const s of [0, 1])
    T(
      o,
      c,
      [plantPoint(s, 0.035, -49), plantPoint(s, 0.965, -49), plantPoint(s, 0.5, -45.7)],
      'concrete',
      C.concrete,
    );
  if (c.detail) {
    plantBlock(o, c, 0.12, 0.88, 0.38, 0.63, -48, -43.2, 'roof');
    const n0 = sub(plantPoint(1, 0, -58), plantPoint(0, 0, -58)),
      len = Math.hypot(n0[0], n0[2]);
    for (let j = 0, count = c.fine ? 30 : 15; j < count; j++)
      for (const side of [-1, 1]) {
        const t = side < 0 ? 0.058 : 0.942,
          a = (j + 0.16) / count,
          b = (j + 0.78) / count;
        const n = [(side * n0[2]) / len, 0, (-side * n0[0]) / len];
        Q(
          o,
          c,
          [
            plantPoint(a, t, -57.6),
            plantPoint(b, t, -57.6),
            plantPoint(b, t, -51.8),
            plantPoint(a, t, -51.8),
          ],
          'glass',
          C.glass,
          n,
        );
      }
    for (const s of [0.22, 0.46, 0.68, 0.81])
      plantBlock(o, c, s, s + 0.055, 0.33, 0.46, -44, -41.8, 'steel');
  }
}
export function buildDamLevel(o, level = 'master') {
  const c = cfg[level];
  if (!c) throw Error('Unknown Mangla tier ' + level);
  embankment(o, c);
  mainSpillway(o, c);
  powerhouse(o, c);
}
