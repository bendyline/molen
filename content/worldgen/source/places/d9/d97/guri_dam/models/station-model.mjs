    for (const z of [-5, 5]) {
      beam(adapter(o, c), 'metal', p([0, 14, z]), p([10, 24, z]), 0.25, 0.25, C.metal);
      beam(adapter(o, c), 'metal', p([10, 14, z]), p([0, 24, z]), 0.25, 0.25, C.metal);
    }
