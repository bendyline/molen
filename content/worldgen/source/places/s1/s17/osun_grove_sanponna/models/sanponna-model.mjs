function sample(controls, detail, isWide) {
  if (detail === 0 && controls.length > 4) {
    const count = isWide ? 6 : 4;
    return Array.from(
      { length: count },
      (_, i) => controls[Math.round((i * (controls.length - 1)) / (count - 1))],
    );
  }
  if (detail < 2) return controls;
  // Subdivide with a Hermite spline while preserving the visible turns at each given section.
  const intervals = detail === 2 ? 2 : 3;
  const sections = [];
  for (let i = 0; i < controls.length - 1; i++) {
    const b = controls[i],
      c = controls[i + 1];
    const a = controls[Math.max(0, i - 1)],
      d = controls[Math.min(i + 2, controls.length - 1)];
    for (let j = 0; j < intervals; j++) {
      const t = j / intervals,
        tt = t * t,
        ttt = tt * t;
      sections.push(
        b.map((v, k) =>
          k < 3
            ? (2 * ttt - 3 * tt + 1) * v +
              (ttt - 2 * tt + t) * (c[k] - a[k]) * 0.39 +
              (3 * tt - 2 * ttt) * c[k] +
              (ttt - tt) * (d[k] - v) * 0.39
            : v + (c[k] - v) * t,
        ),
      );
    }
  }
  return [...sections, controls.at(-1)];
}

function tint(points) {
  const [x, y, z] = points[0].map((value, axis) => (value + points[1][axis] + points[2][axis]) / 3);
  const moisture = Math.max(0, 0.78 - y * 0.2);
  const patches = Math.max(
    0,
    0.35 + 0.44 * Math.sin(x * 2.3 + z * 3.9) + 0.21 * Math.cos(y * 3.8 + z),
  );
  const moss = moisture * patches;
  const tone = 0.9 + 0.12 * Math.sin(x * 4.6 + z * 3.7 - y * 1.9);
  return [
    (0.46 - moss * 0.36) * tone,
    (0.418 - moss * 0.227) * tone,
    (0.333 - moss * 0.275) * tone,
  ];
}

function cast(out, controls, detail, wide = false) {
  const sides = [3, 7, 10, 13, 16][detail];
  const sections = sample(controls, detail, wide);
  const rings = sections.map(([x, y, z, width, depth], i) => {
    const before = sections[Math.max(0, i - 1)],
      after = sections[Math.min(i + 1, sections.length - 1)];
    const axis = normalize(after.slice(0, 3).map((value, n) => value - before[n]));
    const across = normalize(cross(axis, [0, 0, 1]));
    const back = cross(axis, across);
    return Array.from({ length: sides }, (_, k) => {
      const angle = (k * 2 * Math.PI) / sides;
      const p = Math.hypot(x, z) * 0.66 + y;
      const irregular = 1 + 0.108 * Math.sin(3 * angle + p) + 0.06 * Math.cos(5 * angle - p * 2.1);
      const u = Math.cos(angle) * width * irregular;
      const v = Math.sin(angle) * depth * irregular + (wide ? u * 0.26 * Math.sin(p * 2.8) : 0);
      return [x, y, z].map((value, n) => value + across[n] * u + back[n] * v);
    });
  });
  function triangle(a, b, c) {
    const points = [a, b, c];
    out.addTriangle('concrete', 'palette:#ffffff', points, normalFor(a, b, c), null, tint(points));
  }
  for (let k = 0; k < sides; k++) {
    const next = (k + 1) % sides;
    triangle(sections[0].slice(0, 3), rings[0][next], rings[0][k]);
    triangle(sections.at(-1).slice(0, 3), rings.at(-1)[k], rings.at(-1)[next]);
    for (let i = 1; i < rings.length; i++) {
      const [a, b, c, d] = [rings[i - 1][k], rings[i - 1][next], rings[i][next], rings[i][k]];
      triangle(a, b, c);
      triangle(a, c, d);
    }
  }
}

function build(out, detail) {
  for (const sections of dancer) cast(out, sections, detail);
  for (const sections of intertwined) cast(out, sections, detail, true);
  for (const sections of folds) cast(out, sections, detail, true);
  if (detail > 0) for (const sections of rearBands) cast(out, sections, detail, true);
  for (const sections of detail === 0 ? accents.slice(0, 2) : accents) cast(out, sections, detail);
}

