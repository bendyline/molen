function spanAtX(r, x) {
  const zs = [];
  for (let j = 0; j < r.length; j++) {
    const a = r[j],
      b = r[(j + 1) % r.length];
    if (Math.abs(a[0] - x) < 1e-6) zs.push(a[1]);
    if ((a[0] < x && b[0] > x) || (a[0] > x && b[0] < x))
      zs.push(a[1] + ((b[1] - a[1]) * (x - a[0])) / (b[0] - a[0]));
  }
  return [Math.min(...zs), Math.max(...zs)];
}
function shed(o, c, poly) {
  const r = openRing(poly[0]),
    box = bounds(poly),
    corners = [
      [box[0], box[1]],
      [box[2], box[1]],
      [box[2], box[3]],
      [box[0], box[3]],
    ].map(([x, z]) =>
      r.reduce((a, b) => (Math.hypot(a[0] - x, a[1] - z) < Math.hypot(b[0] - x, b[1] - z) ? a : b)),
    ),
    lerp = (a, b, u) => a.map((v, i) => v + (b[i] - v) * u),
    P = (u, t, dy = 0) => {
      const low = lerp(corners[0], corners[1], u),
        high = lerp(corners[3], corners[2], u),
        q = lerp(low, high, (1 - Math.cos(t)) / 2);
      return [q[0], BASE + 12 + 8 * Math.sin(t) + dy, q[1]];
    };
  for (let i = 0; i < c.rows; i++)
    for (let j = 0; j < c.roof; j++) {
      const u0 = i / c.rows,
        u1 = (i + 1) / c.rows,
        a = (j * Math.PI) / c.roof,
        b = ((j + 1) * Math.PI) / c.roof,
        s = j >= c.roof / 4 && j < (3 * c.roof) / 4 ? 'glass' : 'sheet',
        p = [P(u0, a), P(u1, a), P(u1, b), P(u0, b)];
      Q(o, c, p, s, C[s], [0, 1, 0]);
      Q(
        o,
        c,
        p.map((q) => [q[0], q[1] - 0.13, q[2]]),
        s,
        C[s],
        [0, -1, 0],
      );
      if (i === 0 || i === c.rows - 1) {
        const u = i === 0 ? u0 : u1;
        Q(o, c, [P(u, a, -0.13), P(u, b, -0.13), P(u, b), P(u, a)], s, C[s], [
          i === 0 ? -1 : 1,
          0,
          0,
        ]);
      }
      if (j === 0 || j === c.roof - 1) {
        const t = j === 0 ? a : b;
        Q(o, c, [P(u0, t, -0.13), P(u1, t, -0.13), P(u1, t), P(u0, t)], s, C[s], [
          0,
          0,
          j === 0 ? -1 : 1,
        ]);
      }
    }
  if (c.detail) {
    const spacing = c.master ? 3 : c.near ? 8 : c.fine ? 32 : 90,
      count = Math.max(1, Math.ceil((box[2] - box[0]) / spacing));
    for (let i = 0; i <= count; i++) {
      const u = i / count,
        path = Array.from({ length: c.roof + 1 }, (_, j) => P(u, (j * Math.PI) / c.roof, 0.035));
      beamPath(adapter(o, c), 'metal', path, c.fine ? 0.16 : 0.25, 0.18, C.metal);
      if (i % 2 === 0 || i === count)
        for (const t of [0, Math.PI]) {
          const p = P(u, t, -0.2);
          cylinder(o, c, p[0], p[2], c.fine ? 0.18 : 0.25, FOOT, p[1], 'metal');
        }
    }
  } else
    for (const u of [0.01, 0.99])
      for (const t of [0, Math.PI]) {
        const p = P(u, t, -0.2);
        cylinder(o, c, p[0], p[2], 0.3, FOOT, p[1], 'metal');
      }
  if (c.fine)
    for (const t of [Math.PI * 0.25, Math.PI * 0.5, Math.PI * 0.75])
      beamPath(
        adapter(o, c),
        'metal',
        Array.from({ length: c.rows + 1 }, (_, i) => P(i / c.rows, t, 0.04)),
        0.12,
        0.14,
        C.metal,
      );
}
