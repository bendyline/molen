export function buildStationLevel(o, level = 'master', mark = () => {}) {
  const c = cfg[level];
  if (!c) throw Error('Unknown Hamburg tier ' + level);
  for (const p of controls.ground) {
    if (c.detail) solid(o, c, p, FOOT, FLOOR, 'base');
    else panel(o, c, p, FLOOR, 'base');
  }
  mark('actual-side-and-transverse-closed-floors');
  sideRanges(o, c);
  crossHall(o, c);
  portals(o, c);
  mark('whole-wandelhalle-north-range-and-all-side-bays');
  largeShed(o, c);
  mark('complete-bent-barrel-roof-monitor-and-both-glazed-ends');
  for (const t of controls.clocks) clock(o, c, t.cx, t.cz);
  for (const t of controls.cupolas) smallCupola(o, c, t);
  eastPavilion(o, c);
  mark('both-clocks-copper-entrance-turrets-and-east-pavilion');
}
