const inConcourse = (x, z) =>
  controls.concourse.some((p) => {
    let yes = false;
    const r = p[0];
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const a = r[i],
        b = r[j];
      if (a[1] > z !== b[1] > z && x < ((b[0] - a[0]) * (z - a[1])) / (b[1] - a[1]) + a[0])
        yes = !yes;
    }
    return yes;
  });
