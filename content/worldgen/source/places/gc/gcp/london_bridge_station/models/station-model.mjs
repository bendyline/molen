function archBand(o, c, p, u, spring, R0, R1, s = 'stone', d = 0.1, n = c.round) {
  for (let j = 0; j < n; j++) {
    const a = (j / n) * Math.PI,
      b = ((j + 1) / n) * Math.PI;
    Q(
      o,
      c,
      [
        p([u + R0 * Math.cos(a), spring + R0 * Math.sin(a), d]),
        p([u + R0 * Math.cos(b), spring + R0 * Math.sin(b), d]),
        p([u + R1 * Math.cos(b), spring + R1 * Math.sin(b), d]),
        p([u + R1 * Math.cos(a), spring + R1 * Math.sin(a), d]),
      ],
      s,
      C[s],
      sub(p([0, 0, 1]), p([0, 0, 0])),
    );
  }
}
function ringEdges(poly, fn) {
  for (let k = 0; k < poly.length; k++) {
    let r = openRing(poly[k]);
    const area = r.reduce((s, p, i) => {
      const q = r[(i + 1) % r.length];
      return s + p[0] * q[1] - p[1] * q[0];
    }, 0);
    if (area < 0) r = [...r].reverse();
    for (let j = 0; j < r.length; j++) {
      let e = edge(r, j);
      if (k) {
        const p = e.p;
        e = { ...e, N: e.N.map((v) => -v), p: ([u, y, d]) => p([u, y, -d]) };
      }
      fn(e, k);
    }
  }
}

const lerp = (a, b, t) => a + (b - a) * t;
function span(poly, x) {
  const zs = [];
  for (const r of poly)
    for (let j = 0; j < r.length - 1; j++) {
      const a = r[j],
        b = r[j + 1];
      if (Math.abs(a[0] - b[0]) < 1e-9) continue;
      if (x >= Math.min(a[0], b[0]) - 1e-7 && x <= Math.max(a[0], b[0]) + 1e-7)
        zs.push(a[1] + ((b[1] - a[1]) * (x - a[0])) / (b[0] - a[0]));
    }
  return [Math.min(...zs), Math.max(...zs)];
}
function ribbon(o, c, r) {
  if (c === cfg.skyline) {
    panel(o, c, r.poly, 11.7, 'roof');
    return;
  }
  const N = Math.ceil((r.xmax - r.xmin) / c.step),
    xs = [
      ...new Set([
        ...Array.from({ length: N + 1 }, (_, i) => lerp(r.xmin + 1e-5, r.xmax - 1e-5, i / N)),
        ...r.poly[0].map((p) => p[0]).filter((x) => x > r.xmin + 1e-5 && x < r.xmax - 1e-5),
      ]),
    ].sort((a, b) => a - b),
    H = (t) => 11.1 + 0.9 * Math.pow(Math.abs(t * 2 - 1), 1.5),
    P = (x, t, drop = 0) => {
      const [a, b] = span(r.poly, x);
      return [x, H(t) - drop, lerp(a, b, t)];
    };
  for (let i = 0; i < xs.length - 1; i++)
    for (let j = 0; j < c.across; j++) {
      const a = xs[i],
        b = xs[i + 1],
        u = j / c.across,
        v = (j + 1) / c.across;
      Q(o, c, [P(a, u), P(b, u), P(b, v), P(a, v)], 'roof', C.roof, [0, 1, 0]);
      if (c.fine)
        Q(
          o,
          c,
          [P(a, u, 0.18), P(b, u, 0.18), P(b, v, 0.18), P(a, v, 0.18)],
          'wood',
          C.wood,
          [0, -1, 0],
        );
    }
  for (const t of [0, 1]) {
    for (let i = 0; i < xs.length - 1; i++)
      Q(
        o,
        c,
        [P(xs[i], t, 0.3), P(xs[i + 1], t, 0.3), P(xs[i + 1], t), P(xs[i], t)],
        'metal',
        C.metal,
        [0, 0, t === 0 ? -1 : 1],
      );
    if (c.near)
      beamPath(
        adapter(o, c),
        'metal',
        xs.map((x) => P(x, t, 0.12)),
        0.1,
        0.17,
        C.metal,
        false,
      );
  }
  for (const x of [xs[0], xs.at(-1)])
    for (let j = 0; j < c.across; j++) {
      const u = j / c.across,
        v = (j + 1) / c.across;
      Q(o, c, [P(x, u, 0.3), P(x, v, 0.3), P(x, v), P(x, u)], 'metal', C.metal, [
        x === xs[0] ? -1 : 1,
        0,
        0,
      ]);
    }
  const supportStep = c.master ? 15 : c.near ? 30 : c.fine ? 50 : 90;
  for (let x = r.xmin + 12; x < r.xmax - 8; x += supportStep) {
    const [a, b] = span(r.poly, x),
      z = (a + b) / 2;
    box(o, c, x - 0.16, x + 0.16, 8, 10.65, z - 0.16, z + 0.16, 'metal');
    if (c.fine) {
      beam(adapter(o, c), 'metal', [x, 10.2, z], [x, 11.78, a + 0.25], 0.15, 0.2, C.metal);
      beam(adapter(o, c), 'metal', [x, 10.2, z], [x, 11.78, b - 0.25], 0.15, 0.2, C.metal);
    }
  }
  if (c.near) {
    const mid = xs.map((x) => {
      const [a, b] = span(r.poly, x);
      return [x, 8.15, (a + b) / 2];
    });
    beamPath(
      adapter(o, c),
      'base',
      mid,
      Math.min(
        4,
        (span(r.poly, (r.xmin + r.xmax) / 2)[1] - span(r.poly, (r.xmin + r.xmax) / 2)[0]) * 0.4,
      ),
      0.3,
      C.base,
      false,
    );
    if (c.master)
      for (let x = r.xmin + 4; x < r.xmax - 3; x += 4) {
        const [a, b] = span(r.poly, x);
        beam(
          adapter(o, c),
          'metal',
          [x, 11.4, a + 0.15],
          [x, 11.4, b - 0.15],
          0.045,
          0.06,
          C.metal,
        );
      }
  }
}
function glazing(o, c, e, lo, hi, step = 8, surface = 'brick') {
  const count = Math.max(1, Math.floor(e.L / step)),
    holes = c.detail
      ? Array.from({ length: count }, (_, i) => ({
          ring: rect(((i + 0.5) * e.L) / count, lo + 0.3, (e.L / count) * 0.76, hi - lo - 0.6),
          kind: 'glass',
          depth: 0.3,
        }))
      : [];
  wall(o, c, e.p, e.L, lo, hi, holes, surface);
  if (c.fine) for (const y of [lo + 0.1, hi - 0.1]) band(o, c, e, y, 0.15, 'metal', 0.05);
}
