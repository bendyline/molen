function splitRoofRing(ring, zc, lower) {
  const r = openRing(ring),
    result = [];
  for (let i = 0; i < r.length; i++) {
    const a = r[i],
      b = r[(i + 1) % r.length],
      A = lower ? a[1] <= zc : a[1] >= zc,
      B = lower ? b[1] <= zc : b[1] >= zc;
    if (A) result.push(a);
    if (A !== B) result.push([a[0] + ((b[0] - a[0]) * (zc - a[1])) / (b[1] - a[1]), zc]);
  }
  return result;
}
