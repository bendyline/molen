function belt(o, c, e, y, h = 0.22, d = 0.15, s = 'stone') {
  Q(
    o,
    c,
    [e.p([0, y, d]), e.p([e.L, y, d]), e.p([e.L, y + h, d]), e.p([0, y + h, d])],
    s,
    C[s],
    e.N,
  );
  Q(
    o,
    c,
    [e.p([0, y + h, 0]), e.p([e.L, y + h, 0]), e.p([e.L, y + h, d]), e.p([0, y + h, d])],
    s,
    C[s],
    [0, 1, 0],
  );
}
function shell(o, c, poly, lo, hi, s = 'glass', pitch = 4.2) {
  panel(o, c, poly, hi, 'membrane');
  panel(o, c, poly, lo, 'membrane', [0, -1, 0]);
  ringEdges(poly, (e) => {
    if (!c.detail || e.L < 2) {
      wall(o, c, e.p, e.L, lo, hi, [], s);
      return;
    }
    const nx = Math.max(
        1,
        Math.round(
          e.L /
            (c === cfg.district
              ? pitch * 2
              : c === cfg.street && s !== 'glass'
                ? pitch * 2
                : pitch),
        ),
      ),
      ny = Math.max(1, Math.round((hi - lo) / 4.2)),
      w = e.L / nx,
      h = (hi - lo) / ny;
    if (s === 'glass') {
      wall(o, c, e.p, e.L, lo, hi, [], 'glass');
      for (let j = 0; j <= ny; j += c === cfg.district ? 3 : 1)
        belt(o, c, e, lo + j * h, 0.12, 0.06, 'metal');
      if (c.fine)
        for (let j = 0; j <= nx; j += c === cfg.street ? 2 : 1)
          beam(
            adapter(o, c),
            'metal',
            e.p([j * w, lo, 0.07]),
            e.p([j * w, hi, 0.07]),
            0.09,
            0.11,
            C.metal,
          );
    } else {
      const holes = [];
      for (let j = 0; j < nx; j++)
        for (let k = 0; k < ny; k++)
          holes.push({
            ring: rect((j + 0.5) * w, lo + k * h + 0.6, w * 0.7, Math.max(0.3, h - 1.05)),
            kind: 'glass',
            depth: 0.19,
          });
      wall(o, c, e.p, e.L, lo, hi, holes, s);
      if (c.near)
        for (const h of holes)
          beamPath(
            adapter(o, c),
            'metal',
            h.ring.map(([u, y]) => e.p([u, y, 0.04])),
            0.06,
            0.08,
            C.metal,
            true,
          );
    }
    belt(o, c, e, hi - 0.2, 0.2, 0.12, 'metal');
  });
}
function tube(o, c, a, b, r, s = 'metal', n = c.master ? 48 : c.near ? 12 : 4) {
  const D = sub(b, a),
    L = Math.hypot(...D),
    V = D.map((v) => v / L),
    U = Math.abs(V[1]) < 0.9 ? [V[2], 0, -V[0]] : [1, 0, 0],
    ul = Math.hypot(...U);
  for (let i = 0; i < 3; i++) U[i] /= ul;
  const W = cross(V, U),
    at = (p, t) => p.map((v, k) => v + r * (U[k] * Math.cos(t) + W[k] * Math.sin(t)));
  for (let j = 0; j < n; j++) {
    const t = (j / n) * Math.PI * 2,
      u = ((j + 1) / n) * Math.PI * 2,
      N = U.map((v, k) => v * Math.cos((t + u) / 2) + W[k] * Math.sin((t + u) / 2));
    Q(o, c, [at(a, t), at(b, t), at(b, u), at(a, u)], s, C[s], N);
  }
}
function north(o, c) {
  for (const p of controls.northConcourse) {
    solid(o, c, p, -8, 7, 'base');
    shell(o, c, p, 7, 12, 'glass', 3.6);
  }
  for (const p of controls.northOffice) {
    shell(o, c, p, 12, 42, 'glass', 3.3);
    ringEdges(p, (e) => {
      if (!c.detail || e.L < 8) return;
      // Characteristic external silver structural tube family, not a plain glazed cube.
      const n = Math.max(1, Math.round(e.L / (c.near ? 8 : c.fine ? 12 : 20))),
        w = e.L / n;
      for (const y of c === cfg.district ? [12, 41.8] : [12, 22, 32, 41.8]) {
        if (c.fine) tube(o, c, e.p([0, y, 0.55]), e.p([e.L, y, 0.55]), y === 12 ? 0.43 : 0.21);
        else
          beam(adapter(o, c), 'metal', e.p([0, y, 0.55]), e.p([e.L, y, 0.55]), 0.35, 0.35, C.metal);
      }
      if (c.detail)
        for (let j = 0; j < n; j++) {
          const u = j * w,
            v = (j + 1) * w;
          if (c.fine) {
            tube(o, c, e.p([u, 12, 0.58]), e.p([u, 42, 0.58]), 0.23);
            tube(o, c, e.p([u, 12, 0.58]), e.p([v, 22, 0.58]), 0.18);
            tube(o, c, e.p([v, 22, 0.58]), e.p([u, 32, 0.58]), 0.18);
            tube(o, c, e.p([u, 32, 0.58]), e.p([v, 42, 0.58]), 0.18);
          } else
            beam(
              adapter(o, c),
              'metal',
              e.p([u, 12, 0.58]),
              e.p([v, 42, 0.58]),
              0.24,
              0.24,
              C.metal,
            );
        }
      if (c.master)
        for (let u = 1; u < e.L; u += 1.7)
          beam(
            adapter(o, c),
            'metal',
            e.p([u, 11.72, 0]),
            e.p([u, 11.72, 0.9]),
            0.035,
            0.055,
            C.metal,
          );
    });
  }
  for (const z of [-31, 0, 29])
    box(o, c, -125.8, -125.35, -8, 12, z - 0.23, z + 0.23, 'metal', C.metal);
}
function gardenWing(o, c) {
  if (c === cfg.skyline) {
    for (const p of controls.platform) solid(o, c, p, 6.7, 7, 'base');
    for (const p of controls.middleOffice) solid(o, c, p, 13, 38, 'glass');
    for (const p of controls.middleCore) solid(o, c, p, 7, 46, 'glass');
    for (const b of controls.gardenBlocks.filter((b) => [865, 866, 867, 868, 869].includes(b.seed)))
      for (const p of b.polygons) solid(o, c, p, b.min, b.height, b.seed < 868 ? 'glass' : 'brick');
    for (const p of controls.gardenCore) solid(o, c, p, 13, 24, 'brick');
    for (const p of controls.gardenPatches) panel(o, c, p, 24.13, 'garden');
    return;
  }
  // A raised station deck and open approaches, never a ground-level parent cuboid.
  for (const p of controls.platform) solid(o, c, p, 6.7, 7, 'base');
  for (const p of controls.middleOffice) shell(o, c, p, 13, 38, 'glass', 4.3);
  for (const p of controls.middleCore) shell(o, c, p, 7, 46, 'glass', 4.5);
  for (const m of controls.middleSmall) {
    if ([874, 875, 876].includes(m.seed)) continue;
    for (const p of m.polygons) {
      const lo = m.seed === 861 ? 38 : 7;
      shell(o, c, p, lo, m.height, m.seed === 861 ? 'metal' : 'glass', 4.5);
    }
  }
  for (const b of controls.gardenBlocks) {
    if ([870, 871, 872, 873, 863, 864].includes(b.seed)) continue;
    for (const p of b.polygons)
      shell(o, c, p, b.min, b.height, [865, 866, 867].includes(b.seed) ? 'glass' : 'brick', 5);
  }
  for (const p of controls.gardenCore) shell(o, c, p, 13, 24, 'brick', 5.5);
  for (const p of controls.gardenPatches) {
    solid(o, c, p, 24.02, 24.13, 'garden');
    if (c.fine)
      ringEdges(p, (e) => {
        if (e.L < 4) return;
        const a = e.p([0.4, 24.28, -0.25]),
          b = e.p([e.L - 0.4, 24.28, -0.25]);
        beam(adapter(o, c), 'garden', a, b, 0.38, 0.4, C.garden);
      });
  }
  if (c.fine) {
    for (const p of controls.gardenCore)
      ringEdges(p, (e) => {
        beam(
          adapter(o, c),
          'metal',
          e.p([0, 25.0, 0.04]),
          e.p([e.L, 25.0, 0.04]),
          0.055,
          0.06,
          C.metal,
        );
        const n = Math.ceil(e.L / (c.near ? 2.3 : 6));
        for (let j = 0; j <= n; j++)
          beam(
            adapter(o, c),
            'metal',
            e.p([(j / n) * e.L, 24, 0.04]),
            e.p([(j / n) * e.L, 25.0, 0.04]),
            0.045,
            0.05,
            C.metal,
          );
      });
  }
}
function tower(o, c, t) {
  const r = controls.groups[t.seed][0][0],
    w = t.width / 2;
  solid(o, c, [r], -8, 21, 'brick');
  ringEdges([r], (e) => {
    const holes = c.detail
      ? [
          {
            ring: arch(e.L / 2, 22.2, e.L * 0.56, 6.45, 1.75, c.round),
            kind: 'louver',
            depth: 0.32,
          },
        ]
      : [];
    wall(o, c, e.p, e.L, 21, 33.5, holes, 'stone');
    for (const [y, h, d] of [
      [0.5, 0.5, 0.2],
      [8.5, 0.22, 0.14],
      [16.5, 0.22, 0.14],
      [20.7, 0.5, 0.28],
      [21.3, 0.32, 0.19],
      [32.8, 0.3, 0.24],
      [33.5, 0.4, 0.42],
      [34.3, 0.55, 0.55],
    ])
      if (c !== cfg.skyline || y === 34.3) belt(o, c, e, y, h, d);
    if (c.fine) {
      for (const u of [0.32, e.L - 0.32])
        beam(
          adapter(o, c),
          'stone',
          e.p([u, 21.8, 0.15]),
          e.p([u, 32.5, 0.15]),
          0.28,
          0.24,
          C.stone,
        );
      if (c.near)
        for (const h of holes)
          beamPath(
            adapter(o, c),
            'stone',
            h.ring.map(([u, y]) => e.p([u, y, 0.08])),
            0.16,
            0.18,
            C.stone,
            true,
          );
      if (c.near)
        for (let y = 22.4; y < 29; y += c.master ? 0.2 : 0.5)
          beam(
            adapter(o, c),
            'louver',
            e.p([e.L * 0.23, y, -0.15]),
            e.p([e.L * 0.77, y, -0.15]),
            0.07,
            0.09,
            C.louver,
          );
    }
  });
  solid(o, c, [r], 33.5, 35, 'stone');
  const n = c === cfg.skyline ? 4 : c.round * 2,
    levels = [
      [35, w + 0.45],
      [35.7, w + 0.55],
      [36.5, w + 0.35],
      [37.7, w * 0.83],
      [39.4, w * 0.48],
      [40.5, 0.68],
    ],
    at = (y, R, j) => {
      const a = (j / n) * Math.PI * 2,
        sn = Math.sin(a),
        cs = Math.cos(a);
      return [
        t.x + Math.sign(cs) * Math.pow(Math.abs(cs), 0.65) * R,
        y,
        t.z + Math.sign(sn) * Math.pow(Math.abs(sn), 0.65) * R,
      ];
    };
  for (let k = 0; k < levels.length - 1; k++)
    for (let j = 0; j < n; j++) {
      const [y, R] = levels[k],
        [Y, Qr] = levels[k + 1];
      Q(o, c, [at(y, R, j), at(y, R, j + 1), at(Y, Qr, j + 1), at(Y, Qr, j)], 'roof', C.roof, [
        Math.cos(((j + 0.5) / n) * Math.PI * 2),
        0.5,
        Math.sin(((j + 0.5) / n) * Math.PI * 2),
      ]);
    }
  // Close the small dome crown around its spire; no missing roof annulus.
  for (let j = 0; j < n; j++)
    T(
      o,
      c,
      [[t.x, 40.5, t.z], at(40.5, 0.68, j), at(40.5, 0.68, j + 1)],
      'roof',
      C.roof,
      [0, 1, 0],
    );
  if (c.near)
    for (let j = 0; j < n; j += c.master ? 1 : 2)
      beamPath(
        adapter(o, c),
        'metal',
        levels.map(([y, R]) => at(y, R + 0.025, j)),
        0.04,
        0.045,
        C.metal,
      );
  tube(o, c, [t.x, 40.5, t.z], [t.x, 43.8, t.z], 0.16, 'roof', c.round);
  if (c.detail) {
    beam(
      adapter(o, c),
      'metal',
      [t.x - 0.55, 43.2, t.z],
      [t.x + 0.55, 43.2, t.z],
      0.045,
      0.045,
      C.metal,
    );
    beam(adapter(o, c), 'metal', [t.x, 43.6, t.z], [t.x, 44, t.z], 0.05, 0.05, C.metal);
  }
}
function tracks(o, c) {
  if (!c.detail || c === cfg.district) return;
  const n = c.master ? 7 : c.near ? 7 : 4;
  for (let j = 0; j < n; j++) {
    const z = -18 + j * (42 / (n - 1));
    for (const x of [18, 50, 82, 114]) {
      beam(
        adapter(o, c),
        'metal',
        [x, 7.06, z - 0.72],
        [Math.min(x + 31, 129), 7.06, z - 0.72],
        0.06,
        0.075,
        C.metal,
      );
      beam(
        adapter(o, c),
        'metal',
        [x, 7.06, z + 0.72],
        [Math.min(x + 31, 129), 7.06, z + 0.72],
        0.06,
        0.075,
        C.metal,
      );
    }
    if (c.master)
      for (let x = 20; x < 128; x += 1.1)
        beam(adapter(o, c), 'metal', [x, 6.98, z - 1.1], [x, 6.98, z + 1.1], 0.15, 0.12, C.metal);
  }
}
export function buildStationLevel(o, level = 'master') {
  const c = cfg[level];
  if (!c) throw Error('Unknown Cannon Street level ' + level);
  north(o, c);
  gardenWing(o, c);
  for (const t of controls.towers) tower(o, c, t);
  tracks(o, c);
}
export const buildStationSkyline = (o) => buildStationLevel(o, 'skyline');
