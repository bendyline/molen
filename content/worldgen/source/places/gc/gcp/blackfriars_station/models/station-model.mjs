function simplifyRing(r, tol) {
  r = openRing(r).slice();
  let changed = true;
  while (changed && r.length > 4) {
    changed = false;
    for (let i = 0; i < r.length; i++) {
      const a = r[(i + r.length - 1) % r.length],
        b = r[i],
        d = r[(i + 1) % r.length],
        dx = d[0] - a[0],
        dz = d[1] - a[1],
        u = Math.max(
          0,
          Math.min(1, ((b[0] - a[0]) * dx + (b[1] - a[1]) * dz) / (dx * dx + dz * dz)),
        );
      if (Math.hypot(b[0] - a[0] - u * dx, b[1] - a[1] - u * dz) < tol) {
        r.splice(i, 1);
        changed = true;
        break;
      }
    }
  }
  return r;
}

