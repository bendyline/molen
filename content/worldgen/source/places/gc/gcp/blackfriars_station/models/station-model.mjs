function bridge(o, c) {
  slab(o, c, controls.deck, 9.7, 11, 'base');
  const xs = [-148, ...controls.pierXs, 143];
  for (let i = 0; i < xs.length - 1; i++) {
    const mid = (xs[i] + xs[i + 1]) / 2,
      [l, r] = limits(controls.deck, mid),
      zs = c.near
        ? [l + 0.8, l + (r - l) * 0.25, (l + r) / 2, l + (r - l) * 0.75, r - 0.8]
        : [l + 0.8, r - 0.8];
    for (const z of zs) archBand(o, c, xs[i] + 2.5, xs[i + 1] - 2.5, z);
    if (c.fine)
      for (let j = 1; j <= 4; j++) {
        const x = xs[i] + ((xs[i + 1] - xs[i]) * j) / 5,
          [l, r] = limits(controls.deck, x);
        beam(adapter(o, c), 'metal', [x, 9.3, l], [x, 9.3, r], 0.22, 0.35, C.metal);
      }
  }
  for (const side of [0, 1]) {
    const z = side ? 17 : -16;
    box(o, c, -146, 143, 9.3, 9.8, z - 0.2, z + 0.2, 'metal');
  }
  for (const x of [-148, 143]) {
    const [l, r] = limits(controls.deck, x);
    box(o, c, x - 3, x + 3, 0, 9.7, l - 0.5, r + 0.5, 'brick');
  }
  if (c.detail) {
    for (const z of [-14, 0, 15]) box(o, c, -145, 142, 11, 11.3, z - 1.3, z + 1.3, 'concrete');
    for (const z of [-9, -4.5, 5.5, 10.2])
      for (const d of [-0.72, 0.72])
        box(o, c, -145, 142, 11, 11.12, z + d - 0.04, z + d + 0.04, 'metal');
    if (c.near)
      for (let x = -145; x < 143; x += c.master ? 0.65 : 1.8)
        for (const z of [-9, -4.5, 5.5, 10.2])
          box(o, c, x, x + 0.14, 11.01, 11.065, z - 1, z + 1, 'base');
  }
}
function roof(o, c) {
  const x0 = -172,
    x1 = 173,
    n = c.roofBays,
    w = (x1 - x0) / n;
  for (let i = 0; i < n; i++) {
    const a = x0 + i * w,
      b = a + w,
      [l, r] = limits(controls.roof, (a + b) / 2),
      y0 = 16.2,
      y1 = 18.1,
      p = (u, v, d = 0) => [a + u * w, y0 + (y1 - y0) * u + d, l + (r - l) * v];
    Q(
      o,
      c,
      [p(0, 0), p(1, 0), p(1, 1), p(0, 1)],
      'roof',
      c === cfg.skyline ? C.solar : C.roof,
      [0, 1, 0],
    );
    Q(
      o,
      c,
      [p(0, 1, -0.18), p(1, 1, -0.18), p(1, 0, -0.18), p(0, 0, -0.18)],
      'roof',
      C.roof,
      [0, -1, 0],
    );
    for (const side of [0, 1])
      Q(o, c, [p(0, side, -0.18), p(1, side, -0.18), p(1, side), p(0, side)], 'roof', C.roof, [
        0,
        0,
        side ? 1 : -1,
      ]);
    Q(
      o,
      c,
      [
        [b, y0 - 0.18, l],
        [b, y1, l],
        [b, y1, r],
        [b, y0 - 0.18, r],
      ],
      'glass',
      C.glass,
      [1, 0, 0],
    );
    if (c.detail) {
      const across = c.master ? 16 : c.near ? 8 : c.fine ? 4 : 1,
        along = c.master ? 8 : c.near ? 4 : c.fine ? 2 : 1;
      for (let j = 0; j < across; j++)
        for (let k = 0; k < along; k++) {
          const u = (k + 0.08) / along,
            U = (k + 0.94) / along,
            v = (j + 0.06) / across,
            V = (j + 0.94) / across;
          Q(
            o,
            c,
            [p(u, v, 0.025), p(U, v, 0.025), p(U, V, 0.025), p(u, V, 0.025)],
            'solar',
            C.solar,
            [0, 1, 0],
          );
        }
      if (c.near) {
        for (let j = 0; j <= across; j++)
          beam(
            adapter(o, c),
            'roof',
            p(0.015, j / across, 0.04),
            p(0.99, j / across, 0.04),
            0.045,
            0.045,
            C.roof,
          );
        for (let k = 0; k <= along; k++)
          beam(
            adapter(o, c),
            'roof',
            p(k / along, 0.015, 0.04),
            p(k / along, 0.985, 0.04),
            0.045,
            0.045,
            C.roof,
          );
      }
    }
    if (c.detail && (c.fine || i % 5 === 0))
      for (const side of [0, 1]) {
        const z = side ? r - 0.4 : l + 0.4;
        beam(adapter(o, c), 'metal', [a + 1, 11.3, z], [b - 0.3, 16.2, z], 0.16, 0.2, C.metal);
        beam(adapter(o, c), 'metal', [a + 1, 11.3, z], [a + 1, 16.4, z], 0.17, 0.2, C.metal);
      }
  }
  for (const side of [0, 1]) {
    const z = (x) => {
      const p = limits(controls.roof, x);
      return p[side] + (side ? -0.35 : 0.35);
    };
    const X = [-171, -145, -100, -40, 20, 80, 142, 172];
    for (let i = 0; i < X.length - 1; i++) {
      const a = X[i],
        b = X[i + 1],
        A = z(a),
        B = z(b);
      Q(
        o,
        c,
        [
          [a, 12.3, A],
          [b, 12.3, B],
          [b, 15.6, B],
          [a, 15.6, A],
        ],
        'glass',
        C.glass,
        [0, 0, side ? 1 : -1],
      );
      beam(adapter(o, c), 'metal', [a, 11.4, A], [b, 11.4, B], 0.17, 0.2, C.metal);
      if (c.detail)
        for (const y of [12.2, 15.7])
          beam(adapter(o, c), 'metal', [a, y, A], [b, y, B], 0.12, 0.13, C.metal);
    }
  }
}
function glazedPavilion(o, c, plan, floor, top) {
  plan = c === cfg.skyline ? simplifyRing(plan, 1.5) : plan;
  slab(o, c, plan, floor - 0.7, floor, 'base');
  slab(o, c, plan, top - 0.35, top, 'roof');
  outlineBeam(o, c, plan, top - 0.15, c.near ? 0.18 : 0.12, 'metal');
  const ring = openRing(plan);
  for (let i = 0; i < ring.length; i++) {
    const { p, L } = edge(ring, i),
      holes = [];
    if (c.detail && L > 7) {
      const n = Math.floor(L / 7);
      for (let j = 0; j < n; j++)
        holes.push({
          ring: rect(
            ((j + 0.5) * L) / n,
            floor,
            Math.min(3.2, L / n - 1.4),
            Math.min(3.4, top - floor - 0.6),
          ),
          kind: 'doorGlass',
        });
    }
    wall(o, c, p, L, floor, top - 0.35, holes, 'glass');
    if (c.fine) {
      const n = Math.max(1, Math.ceil(L / 5));
      for (let j = 0; j <= n; j++)
        beam(
          adapter(o, c),
          'metal',
          p([(j * L) / n, floor, 0.06]),
          p([(j * L) / n, top - 0.35, 0.06]),
          0.12,
          0.16,
          C.metal,
        );
      beam(
        adapter(o, c),
        'metal',
        p([0, Math.min(top - 0.7, floor + 3.4), 0.06]),
        p([L, Math.min(top - 0.7, floor + 3.4), 0.06]),
        0.12,
        0.16,
        C.metal,
      );
    }
  }
}
