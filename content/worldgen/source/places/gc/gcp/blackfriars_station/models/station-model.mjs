function limits(ring, x) {
  const z = [];
  ring = openRing(ring);
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i],
      b = ring[(i + 1) % ring.length];
    if ((a[0] <= x && b[0] > x) || (b[0] <= x && a[0] > x))
      z.push(a[1] + ((x - a[0]) / (b[0] - a[0])) * (b[1] - a[1]));
  }
  return z.length
    ? [Math.min(...z), Math.max(...z)]
    : limits(
        ring,
        Math.max(
          Math.min(x, Math.max(...ring.map((p) => p[0])) - 0.001),
          Math.min(...ring.map((p) => p[0])) + 0.001,
        ),
      );
}
function capsule(x, z, length, width, n) {
  const r = width / 2,
    half = length / 2 - r,
    pts = [];
  for (const sign of [-1, 1])
    for (let i = 0; i <= n; i++) {
      const a = (sign < 0 ? Math.PI : 0) + (i * Math.PI) / n;
      pts.push([x + r * Math.cos(a), z + sign * half + r * Math.sin(a)]);
    }
  return pts;
}
