function ringEdges(poly, fn) {
  for (let k = 0; k < poly.length; k++) {
    let r = openRing(poly[k]);
    const area = r.reduce((s, p, i) => {
      const q = r[(i + 1) % r.length];
      return s + p[0] * q[1] - p[1] * q[0];
    }, 0);
    if (area < 0) r = [...r].reverse();
    for (let j = 0; j < r.length; j++) {
      let e = edge(r, j);
      if (k) {
        const p = e.p;
        e = { ...e, N: e.N.map((v) => -v), p: ([u, y, d]) => p([u, y, -d]) };
      }
      fn(e, k);
    }
  }
}

function center(poly) {
  const r = openRing(poly[0]);
  return [r.reduce((s, p) => s + p[0], 0) / r.length, r.reduce((s, p) => s + p[1], 0) / r.length];
}
function bb(poly) {
  const a = poly.flat();
  return [
    Math.min(...a.map((p) => p[0])),
    Math.min(...a.map((p) => p[1])),
    Math.max(...a.map((p) => p[0])),
    Math.max(...a.map((p) => p[1])),
  ];
}
function hipRoof(o, c, poly, lo, hi, hip = true, id) {
  const b = bb(poly),
    midZ = (b[1] + b[3]) / 2,
    inset = Math.min((b[3] - b[1]) * 0.5, (b[2] - b[0]) * 0.25),
    H = ([x, z]) =>
      lo +
      (hi - lo) *
        Math.max(
          0,
          Math.min(
            1,
            1 - Math.abs(z - midZ) / ((b[3] - b[1]) / 2),
            ...(hip ? [(x - b[0]) / inset, (b[2] - x) / inset] : [1]),
          ),
        ),
    found = controls.roofPatches[id].find(
      (p) => Math.abs(p.key[0] - poly[0][0][0]) < 1e-5 && Math.abs(p.key[1] - poly[0][0][1]) < 1e-5,
    );
  for (const p of found.patches) {
    const rs = p.map((r) => r.slice(0, -1)),
      flat = rs.flat(),
      holes = rs.slice(1).map((_, j) => rs.slice(0, j + 1).reduce((s, r) => s + r.length, 0)),
      ix = earcut(
        flat.flatMap((v) => [v[0], v[2]]),
        holes,
      );
    for (let j = 0; j < ix.length; j += 3)
      T(
        o,
        c,
        ix.slice(j, j + 3).map((i) => flat[i]),
        'roof',
        C.roof,
        [0, 1, 0],
      );
  }
  ringEdges(poly, (e) =>
    Q(
      o,
      c,
      [
        [e.a[0], lo, e.a[1]],
        [e.b[0], lo, e.b[1]],
        [e.b[0], H(e.b), e.b[1]],
        [e.a[0], H(e.a), e.a[1]],
      ],
      'wall',
      C.wall,
      e.N,
    ),
  );
  if (c.fine)
    beam(
      adapter(o, c),
      'metal',
      [b[0] + inset, hi, midZ],
      [b[2] - inset, hi, midZ],
      0.12,
      0.16,
      C.metal,
    );
}
function frames(o, c, e, hole) {
  if (!c.fine) return;
  const r = hole.ring,
    cx = r.reduce((s, p) => s + p[0], 0) / r.length,
    cy = r.reduce((s, p) => s + p[1], 0) / r.length,
    outer = r.map(([u, y]) => [u + Math.sign(u - cx) * 0.07, y + Math.sign(y - cy) * 0.07]);
  for (let j = 0; j < r.length; j++) {
    const k = (j + 1) % r.length;
    if (c.near)
      beam(
        adapter(o, c),
        'light',
        e.p([...r[j], 0.045]),
        e.p([...r[k], 0.045]),
        0.09,
        0.12,
        C.light,
      );
    else
      Q(
        o,
        c,
        [
          e.p([...r[j], 0.04]),
          e.p([...r[k], 0.04]),
          e.p([...outer[k], 0.04]),
          e.p([...outer[j], 0.04]),
        ],
        'light',
        C.light,
        e.N,
      );
  }
}
function buildings(o, c) {
  for (const id of [controls.officePart, ...controls.serviceParts])
    for (const poly of controls.groups[id]) {
      const office = id === controls.officePart,
        b = bb(poly),
        floor = id === 30 ? controls.warehouseFloor : controls.floor,
        wallTop = office ? controls.officeWall : floor + (id === 167 || id === 168 ? 4 : 3.4),
        ridge = office ? controls.officeRidge : wallTop + 1.3;
      solid(o, c, poly, -8, floor, 'base');
      hipRoof(o, c, poly, wallTop, ridge, office || id === 30, id);
      ringEdges(poly, (e) => {
        const rows = office ? 3 : 1,
          n = Math.max(1, Math.round(e.L / (c === cfg.district ? 12 : c === cfg.street ? 7 : 4.6))),
          w = e.L / n,
          holes = [];
        if (c.detail && e.L > 2)
          for (let j = 0; j < n; j++)
            for (let k = 0; k < rows; k++) {
              const door = k === 0 && j === Math.floor(n / 2) && e.N[1] === 0 && e.N[2] > 0.5,
                ry = office ? 2.75 : 2.2;
              holes.push({
                ring: rect(
                  (j + 0.5) * w,
                  floor + (door ? 0 : 0.65) + k * ry,
                  Math.min(1.55, w * 0.65),
                  door ? 2.25 : 1.65,
                ),
                kind: door ? 'opening' : 'glass',
                depth: 0.17,
              });
            }
        wall(o, c, e.p, e.L, floor, wallTop, holes, 'wall');
        if (c.detail) {
          band(o, c, e, floor + 0.2, 0.23, 'red', 0.035);
          band(o, c, e, wallTop - 0.12, 0.2, 'light', 0.14);
        }
        for (const h of holes) frames(o, c, e, h);
        if (office && c.near)
          for (let u = 0; u < e.L; u += c.master ? 1.4 : 3.2)
            beam(
              adapter(o, c),
              'light',
              e.p([u, floor, 0.015]),
              e.p([u, wallTop, 0.015]),
              0.04,
              0.05,
              C.light,
            );
      });
      if (office && c.fine) {
        for (const x of [b[0] + 6, b[2] - 6])
          box(
            o,
            c,
            x - 0.5,
            x + 0.5,
            controls.officeRidge - 0.4,
            controls.officeRidge + 0.8,
            (b[1] + b[3]) / 2 - 0.45,
            (b[1] + b[3]) / 2 + 0.45,
            'soffit',
          );
        if (c.master)
          for (let j = 0; j < 4; j++) {
            const x = b[0] + ((b[2] - b[0]) * (j + 0.5)) / 4,
              z = b[3] - 0.2;
            box(
              o,
              c,
              x - 0.65,
              x + 0.65,
              wallTop + 0.1,
              wallTop + 0.75,
              z - 1.8,
              z - 0.1,
              'soffit',
            );
          }
      }
    }
}
function canopyHeight(p, z) {
  const w = p.name.startsWith('northern') ? 4 : 2.8;
  return (
    controls.eave + (controls.ridge - controls.eave) * Math.max(0, 1 - Math.abs(z - p.centerZ) / w)
  );
}
function platforms(o, c) {
  for (const p of controls.platforms) {
    for (const poly of p.polys) solid(o, c, poly, -8, controls.platformFloor, 'base');
    const z = p.centerZ,
      w = p.name.startsWith('northern') ? 4 : 2.8,
      b = p.bounds;
    for (const poly of p.roofPanels) {
      const rs = poly.map(openRing),
        all = rs.flat(),
        hole = rs.slice(1).map((_, j) => rs.slice(0, j + 1).reduce((s, r) => s + r.length, 0));
      const tris = earcut(all.flat(), hole);
      for (let j = 0; j < tris.length; j += 3) {
        const A = tris.slice(j, j + 3).map((i) => all[i]),
          ps = A.map(([x, Z]) => [x, canopyHeight(p, Z), Z]);
        T(o, c, ps, 'roof', C.roof, [0, 1, 0]);
        T(
          o,
          c,
          ps.map(([x, y, z]) => [x, y - 0.16, z]),
          'soffit',
          C.soffit,
          [0, -1, 0],
        );
      }
      ringEdges(poly, (e) =>
        Q(
          o,
          c,
          [
            [e.a[0], canopyHeight(p, e.a[1]) - 0.16, e.a[1]],
            [e.b[0], canopyHeight(p, e.b[1]) - 0.16, e.b[1]],
            [e.b[0], canopyHeight(p, e.b[1]), e.b[1]],
            [e.a[0], canopyHeight(p, e.a[1]), e.a[1]],
          ],
          'roof',
          C.roof,
          e.N,
        ),
      );
    }
    if (!c.detail) continue;
    const pitch = c.master ? 4.8 : c.near ? 7.5 : c.fine ? 18 : 60;
    for (let x = b[0] + 14; x < b[2] - 9; x += pitch) {
      if (x > -47 && x < -20) continue;
      for (const d of p.name.startsWith('northern') ? [-1.8, 1.8] : [0]) {
        const y = canopyHeight(p, z + d) - 0.52;
        roundColumn(o, c, [x, z + d], controls.platformFloor, y, c.near ? 0.15 : 0.21, 'metal');
        if (c.fine) {
          for (const side of [-1, 1])
            beam(
              adapter(o, c),
              'metal',
              [x, y - 1.1, z + d],
              [x, controls.eave - 0.2, z + side * (w - 0.25)],
              0.13,
              0.16,
              C.metal,
            );
          beam(
            adapter(o, c),
            'metal',
            [x, controls.eave - 0.18, z - w],
            [x, controls.eave - 0.18, z + w],
            0.15,
            0.18,
            C.metal,
          );
        }
      }
      if (c.near) {
        beamPath(
          adapter(o, c),
          'metal',
          [
            [x, controls.eave - 0.2, z - w],
            [x, controls.ridge - 0.2, z],
            [x, controls.eave - 0.2, z + w],
          ],
          0.11,
          0.13,
          C.metal,
        );
        if (c.master)
          for (const dz of [-w * 0.72, -w * 0.34, 0, w * 0.34, w * 0.72])
            beam(
              adapter(o, c),
              'metal',
              [x, canopyHeight(p, z + dz) - 0.22, z + dz],
              [Math.min(x + pitch, b[2] - 8), canopyHeight(p, z + dz) - 0.22, z + dz],
              0.08,
              0.1,
              C.metal,
            );
      }
    }
    if (c.fine) {
      for (const poly of p.polys)
        ringEdges(poly, (e) => {
          beam(
            adapter(o, c),
            'light',
            e.p([0, controls.platformFloor + 0.025, -0.25]),
            e.p([e.L, controls.platformFloor + 0.025, -0.25]),
            0.35,
            0.04,
            C.light,
          );
          if (c.near && e.L > 20)
            for (let u = 1; u < e.L - 1; u += c.master ? 0.6 : 2.5)
              boxAt(o, c, e, u, controls.platformFloor + 0.03, 0.035, 0.035, -0.5, 'light');
        });
      if (p.name.startsWith('southern'))
        for (let x = b[0] + 2; x < b[2] - 2; x += c.master ? 1.4 : c.near ? 2.8 : 12) {
          beam(
            adapter(o, c),
            'metal',
            [x, controls.platformFloor, z + w + 0.45],
            [x, controls.platformFloor + 1.65, z + w + 0.45],
            0.06,
            0.07,
            C.metal,
          );
          if (c.near)
            Q(
              o,
              c,
              [
                [x, controls.platformFloor + 0.3, z + w + 0.46],
                [Math.min(x + 2.8, b[2] - 2), controls.platformFloor + 0.3, z + w + 0.46],
                [Math.min(x + 2.8, b[2] - 2), controls.platformFloor + 1.5, z + w + 0.46],
                [x, controls.platformFloor + 1.5, z + w + 0.46],
              ],
              'metal',
              C.metal,
              [0, 0, 1],
            );
        }
    }
  }
}
function boxAt(o, c, e, u, y, w, h, d, s) {
  Q(
    o,
    c,
    [
      e.p([u - w / 2, y, d]),
      e.p([u + w / 2, y, d]),
      e.p([u + w / 2, y + h, d]),
      e.p([u - w / 2, y + h, d]),
    ],
    s,
    C[s],
    e.N,
  );
}
function railings(o, c, a, b, y0, y1, width) {
  const dx = b[0] - a[0],
    dz = b[1] - a[1],
    L = Math.hypot(dx, dz),
    U = [dx / L, dz / L],
    N = [U[1], -U[0]],
    pitch = c.master ? 1.2 : c.near ? 2 : c.fine ? 4 : 14;
  for (const side of [-1, 1]) {
    const A = [a[0] + (N[0] * side * width) / 2, y0, a[1] + (N[1] * side * width) / 2],
      B = [b[0] + (N[0] * side * width) / 2, y1, b[1] + (N[1] * side * width) / 2];
    for (const h of [c.fine ? 0.5 : 1.1, 1.15]) {
      if (!c.fine && h === 1.1) continue;
      beam(
        adapter(o, c),
        'metal',
        [A[0], A[1] + h, A[2]],
        [B[0], B[1] + h, B[2]],
        0.06,
        0.065,
        C.metal,
      );
    }
    for (let u = 0; u <= L; u += pitch) {
      const t = u / L,
        x = A[0] + (B[0] - A[0]) * t,
        y = A[1] + (B[1] - A[1]) * t,
        z = A[2] + (B[2] - A[2]) * t;
      beam(adapter(o, c), 'metal', [x, y, z], [x, y + 1.15, z], 0.06, 0.075, C.metal);
    }
  }
}
function crossing(o, c) {
  const [a, b] = controls.bridge,
    L = Math.hypot(b[0] - a[0], b[1] - a[1]),
    N = [(b[1] - a[1]) / L, -(b[0] - a[0]) / L],
    width = 3.3,
    plan = [
      a.map((v, i) => v + (N[i] * width) / 2),
      b.map((v, i) => v + (N[i] * width) / 2),
      b.map((v, i) => v - (N[i] * width) / 2),
      a.map((v, i) => v - (N[i] * width) / 2),
    ];
  slab(o, c, plan, controls.bridgeFloor - 0.45, controls.bridgeFloor, 'stone');
  if (c.detail) railings(o, c, a, b, controls.bridgeFloor, controls.bridgeFloor, width);
  if (c.fine)
    for (const t of [0, 0.32, 0.73, 1]) {
      const x = a[0] + (b[0] - a[0]) * t,
        z = a[1] + (b[1] - a[1]) * t;
      for (const side of [-1, 1]) {
        const X = x + N[0] * side * 0.9,
          Z = z + N[1] * side * 0.9;
        box(o, c, X - 0.3, X + 0.3, -8, controls.bridgeFloor - 1.1, Z - 0.3, Z + 0.3, 'stone');
        beam(
          adapter(o, c),
          'stone',
          [X, controls.bridgeFloor - 2, Z],
          [x + N[0] * side * 1.5, controls.bridgeFloor - 0.4, z + N[1] * side * 1.5],
          0.4,
          0.45,
          C.stone,
        );
      }
    }
  for (const f of controls.stairs) {
    const dx = f.b[0] - f.a[0],
      dz = f.b[1] - f.a[1],
      L = Math.hypot(dx, dz),
      N = [dz / L, -dx / L],
      P = (t, y, d) => [f.a[0] + dx * t + N[0] * d, y, f.a[1] + dz * t + N[1] * d],
      n = c.master
        ? Math.ceil((f.top - f.bottom) / 0.15)
        : c.near
          ? Math.ceil((f.top - f.bottom) / 0.19)
          : c.fine
            ? 18
            : 3,
      w = 2.6;
    Q(
      o,
      c,
      [
        P(0, f.top - 0.3, -w / 2),
        P(1, f.bottom - 0.3, -w / 2),
        P(1, f.bottom - 0.3, w / 2),
        P(0, f.top - 0.3, w / 2),
      ],
      'stone',
      C.stone,
      [0, -1, 0],
    );
    for (let j = 0; j < n; j++) {
      const t = j / n,
        u = (j + 1) / n,
        y = f.top + (f.bottom - f.top) * u;
      Q(
        o,
        c,
        [P(t, y, -w / 2), P(u, y, -w / 2), P(u, y, w / 2), P(t, y, w / 2)],
        'stone',
        C.stone,
        [0, 1, 0],
      );
      const prev = f.top + (f.bottom - f.top) * t;
      Q(
        o,
        c,
        [P(t, y, -w / 2), P(t, y, w / 2), P(t, prev, w / 2), P(t, prev, -w / 2)],
        'stone',
        C.stone,
        [-dx / L, 0, -dz / L],
      );
    }
    if (c.detail) {
      railings(o, c, f.a, f.b, f.top, f.bottom, w);
      for (const d of [-w / 2, w / 2])
        beam(
          adapter(o, c),
          'stone',
          P(0, f.top - 0.2, d),
          P(1, f.bottom - 0.2, d),
          0.2,
          0.4,
          C.stone,
        );
    }
  }
}
export function buildStationLevel(o, level = 'master') {
  const c = cfg[level];
  if (!c) throw Error('Unknown Kuskovo tier ' + level);
  buildings(o, c);
  platforms(o, c);
  crossing(o, c);
}
export const buildStationSkyline = (o) => buildStationLevel(o, 'skyline');
export const buildStationDistrict = (o) => buildStationLevel(o, 'district');
export const buildStationStreet = (o) => buildStationLevel(o, 'street');
export const buildStationCloseup = (o) => buildStationLevel(o, 'closeup');
