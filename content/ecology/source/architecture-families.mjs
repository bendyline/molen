// Ordinary building priors. These are deliberately broad material/construction families,
// not inferred age, ethnicity, or claims about any particular mapped building.
//
// A family says what an ordinary building there is made of and roofed with:
//   walls      weighted wall materials for homes, each with its own colors (brick colors stay on
//              brick). A third of a home palette's weight is clear hue; see the medium-fi guide.
//   roofs      weighted pitched roof coverings, each with its own colors.
//   flat       share of homes with a flat roof (0 none, 1 all), and `flatRoof` its colors.
//   pitch      degrees; eaves in meters.
//   urban      'traditional': blocks of flats, shops and civic buildings are built like the
//              houses (an old town's fabric) and keep a pitched roof through `pitchedLevels`
//              storeys. 'modern': they are rendered concrete under flat roofs.
//   partyRidge ridge of a house in a row: 'between' the party walls (eaves to the street) or
//              'along' them (a gable to the street).
//   paint      colors of shutters and door leaves.
//   flatByUse  flat share for one use where it differs (a region's farmhouses keep their tile
//              while its town plots go flat).
// Colors are albedo in the medium-fi bands: walls a step light (tinting darkens them), slate and
// asphalt at 35-50% lightness, clay tile at 50-62%. How a family lays out the lots it invents is
// in architecture-lots.mjs.

