/** Planted and rough-ground forms for a habitat; every list may be missing. */
export function gardenComposition(name) {
  const zone = ZONE_BY_HABITAT[name];
  if (zone === undefined) throw new Error(`No garden zone for habitat ${name}`);
  const lists = ZONES[zone];
  // The north Pacific coast is past where maples are grown as a matter of course: its yards
  // keep the hardier small trees and a dwarf conifer.
  if (name === 'pacific_hypermaritime')
    return {
      zone,
      ...lists,
      yardTrees: [['arborvitae', 2], 'dogwood', 'purple_plum', 'laurel_screen', 'mugo'],
    };
  return { zone, ...lists };
}
