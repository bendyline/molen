  means = read('surface-means.json');
const linear = (hex) =>
    hex.match(/../g).map((s) => {
      const v = parseInt(s, 16) / 255;
      return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
    }),
  palette = {
    wall: linear('d1cfc4'),
    metal: linear('bcc4c9'),
    seat: linear('4eafa5'),
    seat2: linear('438d85'),
    seat3: linear('86b8a5'),
    panel: linear('dce0de'),
    roof: linear('e1e2d8'),
    glass: [1, 1, 1],
    turf: linear('8ba574'),
    apron: linear('aaa79a'),
    goal: linear('e8be48'),
    mark: linear('ece8d8'),
    display: linear('4f5b67'),
  };

function build(out, detail) {
  const emit = (role, points, target) => {
    let ps = points.map((p) => p.map(Math.fround));
    const first = ps
      .slice(2)
      .map((p, i) => normalFor(ps[0], ps[i + 1], p))
      .find((n) => Math.hypot(...n) > 0.5);
    if (!first) return;
    if (first.reduce((n, v, k) => n + v * target[k], 0) < 0) ps = ps.toReversed();
    const tint = palette[role],
      color = detail === 0 ? tint.map((v, k) => v * (means[role]?.[k] ?? 1)) : tint;
    for (let i = 1; i < ps.length - 1; i++) {
      const t = [ps[0], ps[i], ps[i + 1]];
      if (
        Math.hypot(
          ...cross(
            t[1].map((v, k) => v - t[0][k]),
            t[2].map((v, k) => v - t[0][k]),
          ),
        ) < 1e-7
      )
        continue;
      out.addTriangle(
        role,
        'palette:#ffffff',
        t,
        normalFor(...t),
        t.map((p) =>
          Math.abs(target[1]) > 0.5
            ? [p[0], p[2]]
            : Math.abs(target[0]) > Math.abs(target[2])
              ? [p[2], p[1]]
              : [p[0], p[1]],
        ),
        color,
      );
    }
  };
  buildFonteStadium(emit, detail, r);
}
export const buildFonteSkyline = (o) => build(o, 0),
  buildFonteDistrict = (o) => build(o, 1),
  buildFonteStreet = (o) => build(o, 2),
  buildFonteCloseup = (o) => build(o, 3);
