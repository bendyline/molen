const source = new URL(
    '../../../content/worldgen/source/places/th/ths/ahmad_bin_ali_stadium/',
    import.meta.url,
  ),
  read = (n) => JSON.parse(readFileSync(new URL(n, source), 'utf8')),
  frame = read('map-frame.json'),
  r = frame.reconstruction,
  scope = read('review-scope.json'),
  means = read('surface-means.json');
const linear = (hex) =>
    hex.match(/../g).map((s) => {
      const v = parseInt(s, 16) / 255;
      return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
    }),
  palette = {
    wall: linear('c7c6b6'),
    service: linear('7e8c8b'),
    metal: linear('dddccc'),
    seatRed: linear('b16e71'),
    seatDark: linear('666d72'),
    mark: linear('ece9d8'),
    display: linear('495660'),
    turf: linear('8da575'),
    glass: [1, 1, 1],
    screen: linear('c8b99a'),
    roof: linear('e3dfc9'),
  };

function build(out, detail) {
  const emit = (role, points, target) => {
    let ps = points.map((p) => p.map(Math.fround));
    const first = ps
      .slice(2)
      .map((p, i) => normalFor(ps[0], ps[i + 1], p))
      .find((n) => Math.hypot(...n) > 0.5);
    if (!first) return;
    if (first.reduce((n, v, k) => n + v * target[k], 0) < 0) ps = ps.toReversed();
    const tint = palette[role],
      color = detail === 0 ? tint.map((v, k) => v * (means[role]?.[k] ?? 1)) : tint;
    for (let i = 1; i < ps.length - 1; i++) {
      const t = [ps[0], ps[i], ps[i + 1]];
      if (
        Math.hypot(
          ...cross(
            t[1].map((v, k) => v - t[0][k]),
            t[2].map((v, k) => v - t[0][k]),
          ),
        ) < 1e-7
      )
        continue;
      out.addTriangle(
        role,
        'palette:#ffffff',
        t,
        normalFor(...t),
        t.map((p) => [p[0], p[2]]),
        color,
      );
    }
  };
  buildRayyanStadium(emit, detail, r);
}
export const buildRayyanSkyline = (o) => build(o, 0),
  buildRayyanDistrict = (o) => build(o, 1),
  buildRayyanStreet = (o) => build(o, 2),
  buildRayyanCloseup = (o) => build(o, 3);
