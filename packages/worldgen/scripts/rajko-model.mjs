const source = new URL(
    '../../../content/worldgen/source/places/sr/sry/rajko_mitic_stadium/',
    import.meta.url,
  ),
  read = (n) => JSON.parse(readFileSync(new URL(n, source), 'utf8')),
  frame = read('map-frame.json'),
  r = frame.reconstruction,
  scope = read('review-scope.json'),
  means = read('surface-means.json');
const linear = (hex) =>
    hex.match(/../g).map((s) => {
      const v = parseInt(s, 16) / 255;
      return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
    }),
  palette = {
    wall: linear('d2cec5'),
    metal: linear('c9ccc6'),
    seatRed: linear('bf5553'),
    seatPale: linear('d7d2c5'),
    mark: linear('eae7d8'),
    display: linear('4f5c67'),
    turf: linear('8da575'),
    glass: [1, 1, 1],
    roof: linear('d0d1c9'),
    accent: linear('c44e4a'),
    brick: linear('cfad8b'),
    track: linear('b77f6e'),
  };

function build(out, detail) {
  const emit = (role, points, target) => {
    let ps = points.map((p) => p.map(Math.fround));
    const first = ps
      .slice(2)
      .map((p, i) => normalFor(ps[0], ps[i + 1], p))
      .find((n) => Math.hypot(...n) > 0.5);
    if (!first) return;
    if (first.reduce((n, v, k) => n + v * target[k], 0) < 0) ps = ps.toReversed();
    const tint = palette[role],
      color = detail === 0 ? tint.map((v, k) => v * (means[role]?.[k] ?? 1)) : tint;
    for (let i = 1; i < ps.length - 1; i++) {
      const t = [ps[0], ps[i], ps[i + 1]];
      if (
        Math.hypot(
          ...cross(
            t[1].map((v, k) => v - t[0][k]),
            t[2].map((v, k) => v - t[0][k]),
          ),
        ) < 1e-7
      )
        continue;
      out.addTriangle(
        role,
        'palette:#ffffff',
        t,
        normalFor(...t),
        t.map((p) =>
          Math.abs(target[1]) > 0.5
            ? [p[0], p[2]]
            : Math.abs(target[0]) > Math.abs(target[2])
              ? [p[2], p[1]]
              : [p[0], p[1]],
        ),
        color,
      );
    }
  };
  buildRajkoStadium(emit, detail, r);
}
export const buildRajkoSkyline = (o) => build(o, 0),
  buildRajkoDistrict = (o) => build(o, 1),
  buildRajkoStreet = (o) => build(o, 2),
  buildRajkoCloseup = (o) => build(o, 3);
