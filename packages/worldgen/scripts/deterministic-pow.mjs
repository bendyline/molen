// Compute y+TAIL = log(x) where the rounded result is y and TAIL has about
// additional 15 bits precision. (ixhi, ixlo) is the bit representation of x,
// normalized in the subnormal range using the sign bit for the exponent.
function logInline(ixhi, ixlo) {
  // tmp = ix - OFF, OFF = 0x3fe6955500000000 (low word 0: no borrow).
  const tmphi = (ixhi - 0x3fe69555) | 0;
  const i = (tmphi >>> 13) & 127; // (tmp >> (52 - 7)) % N
  const k = tmphi >> 20; // (int64_t) tmp >> 52, arithmetic
  const izhi = (ixhi - (tmphi & 0xfff00000)) | 0; // ix - (tmp & 0xfffULL << 52)
  const izlo = ixlo;
  I32[HI] = izhi;
  I32[LO] = izlo;
  const z = F64[0];
  const kd = k;

  const t3 = 3 * i;
  const invc = LOG_TAB[t3];
  const logc = LOG_TAB[t3 + 1];
  const logctail = LOG_TAB[t3 + 2];

  // zhi = asdouble ((iz + (1ULL << 31)) & (-1ULL << 32))
  I32[HI] = (izhi + (izlo >>> 31)) | 0;
  I32[LO] = 0;
  const zhi = F64[0];
  const zlo = z - zhi;
  const rhi = zhi * invc - 1.0;
  const rlo = zlo * invc;
  const r = rhi + rlo;

  // k*Ln2 + log(c) + r.
  const t1 = kd * Ln2hi + logc;
  const t2 = t1 + r;
  const lo1 = kd * Ln2lo + logctail;
  const lo2 = t1 - t2 + r;

  const ar = A0 * r;
  const ar2 = r * ar;
  const ar3 = r * ar2;
  const arhi = A0 * rhi;
  const arhi2 = rhi * arhi;
  const hi = t2 + arhi2;
  const lo3 = rlo * (ar + arhi);
  const lo4 = t2 - hi + arhi2;
  // p = log1p(r) - r - A[0]*r*r.
  const p = ar3 * (A1 + r * A2 + ar2 * (A3 + r * A4 + ar2 * (A5 + r * A6)));
  const lo = lo1 + lo2 + lo3 + lo4 + p;
  const y = hi + lo;
  logTail = hi - y + lo;
  return y;
}

// Handle cases that may overflow or underflow when computing scale*(1+tmp).
// (sbhi, sblo) is the bit representation of scale; kilo is the low 32 bits of ki.
function specialcase(tmp, sbhi, sblo, kilo) {
  if ((kilo & 0x80000000) === 0) {
    // k > 0, the exponent of scale might have overflowed by <= 460.
    I32[HI] = (sbhi - 0x3f100000) | 0; // sbits -= 1009ull << 52
    I32[LO] = sblo;
    const scale = F64[0];
    return P2_1009 * (scale + scale * tmp);
  }
  // k < 0, need special care in the subnormal range.
  const sbhi2 = (sbhi + 0x3fe00000) | 0; // sbits += 1022ull << 52
  I32[HI] = sbhi2;
  I32[LO] = sblo;
  const scale = F64[0];
  let y = scale + scale * tmp;
  if (Math.abs(y) < 1.0) {
    let one = 1.0;
    if (y < 0.0) one = -1.0;
    let lo = scale - y + scale * tmp;
    const hi = one + y;
    lo = one - hi + y + lo;
    y = hi + lo - one;
    // Fix the sign of 0.
    if (y === 0.0) y = sbhi2 < 0 ? -0.0 : 0.0;
  }
  return P2_M1022 * y;
}

// Computes sign*exp(x+xtail) where |xtail| < 2^-8/N and |xtail| <= |x|.
// signBias is SIGN_BIAS or 0 and sets the sign to -1 or 1.
function expInline(x, xtail, signBias) {
  F64[0] = x;
  const xhi = I32[HI];
  let abstop = (xhi >>> 20) & 0x7ff;
  // top12(0x1p-54) = 0x3c9, top12(512.0) = 0x408, top12(1024.0) = 0x409
  if ((abstop - 0x3c9) >>> 0 >= 0x408 - 0x3c9) {
    if ((abstop - 0x3c9) >>> 0 >= 0x80000000) {
      // Avoid spurious underflow for tiny x (WANT_ROUNDING).
      const one = 1.0 + x;
      return signBias ? -one : one;
    }
    if (abstop >= 0x409) {
      // __math_uflow / __math_oflow (sign_bias)
      if (xhi < 0) return signBias ? -0.0 : 0.0;
      return signBias ? -Infinity : Infinity;
    }
    // Large x is special cased below.
    abstop = 0;
  }

  // exp(x) = 2^(k/N) * exp(r), with exp(r) in [2^(-1/2N),2^(1/2N)].
  const z = InvLn2N * x;
  let kd = z + Shift;
  F64[0] = kd;
  const kilo = I32[LO]; // low 32 bits of ki = asuint64(kd); only these are used
  kd -= Shift;
  let r = x + kd * NegLn2hiN + kd * NegLn2loN;
  r += xtail;
  // 2^(k/N) ~= scale * (1 + tail).
  const idx = kilo & 127; // ki % N (tables are pre-split per k)
  const tophi = (kilo + signBias) << 13; // hi word of (ki + sign_bias) << 45
  const tail = EXP_TAIL[idx];
  const sbhi = (EXP_SB_HI[idx] + tophi) | 0; // sbits = T[idx + 1] + top
  const sblo = EXP_SB_LO[idx];
  const r2 = r * r;
  const tmp = tail + r + r2 * (C2 + r * C3) + r2 * r2 * (C4 + r * C5);
  if (abstop === 0) return specialcase(tmp, sbhi, sblo, kilo);
  I32[HI] = sbhi;
  I32[LO] = sblo;
  const scale = F64[0];
  return scale + scale * tmp;
}

// Returns 0 if not int, 1 if odd int, 2 if even int. (iyhi, iylo) is the bit
// representation of a non-zero finite floating-point value.
function checkint(iyhi, iylo) {
  const e = (iyhi >>> 20) & 0x7ff;
  if (e < 0x3ff) return 0;
  if (e > 0x3ff + 52) return 2;
  const s = 0x3ff + 52 - e; // number of fraction bits, 0..52
  if (s >= 32) {
    const sh = s - 32; // 0..20
    if (iylo !== 0 || (iyhi & ((1 << sh) - 1)) !== 0) return 0;
    return (iyhi >>> sh) & 1 ? 1 : 2;
  }
  if (s > 0 && iylo << (32 - s) !== 0) return 0;
  return (iylo >>> s) & 1 ? 1 : 2;
}

// Returns true if (hi, lo) is the bit representation of 0, infinity or nan.
function zeroinfnan(hi, lo) {
  const a = hi & 0x7fffffff;
  return (a === 0 && lo === 0) || a >= 0x7ff00000;
}

// pow (x, y) from pow.c.
function corePow(x, y) {
  let signBias = 0;
  F64[0] = x;
  let ixhi = I32[HI];
  let ixlo = I32[LO];
  F64[0] = y;
  const iyhi = I32[HI];
  const iylo = I32[LO];
  let topx = ixhi >>> 20;
  const topy = iyhi >>> 20;
  if ((topx - 0x001) >>> 0 >= 0x7ff - 0x001 || ((topy & 0x7ff) - 0x3be) >>> 0 >= 0x43e - 0x3be) {
    // Special cases: (x < 0x1p-126 or inf or nan) or
    // (|y| < 0x1p-65 or |y| >= 0x1p63 or nan).
    if (zeroinfnan(iyhi, iylo)) {
      if ((iyhi & 0x7fffffff) === 0 && iylo === 0) return 1.0; // 2 * iy == 0
      if (ixhi === 0x3ff00000 && ixlo === 0) return 1.0; // ix == asuint64 (1.0)
      if (Number.isNaN(x) || Number.isNaN(y)) return NaN; // x + y (canonical NaN)
      if ((ixhi & 0x7fffffff) === 0x3ff00000 && ixlo === 0) return 1.0;
      // |x|<1 && y==inf or |x|>1 && y==-inf.
      if ((ixhi & 0x7fffffff) < 0x3ff00000 === iyhi >= 0) return 0.0;
      return y * y;
    }
    if (zeroinfnan(ixhi, ixlo)) {
      let x2 = x * x;
      if (ixhi < 0 && checkint(iyhi, iylo) === 1) {
        x2 = -x2;
        signBias = 1;
      }
      // WANT_ERRNO: __math_divzero (sign_bias)
      if (x === 0 && iyhi < 0) return (signBias ? -1.0 : 1.0) / 0.0;
      return iyhi < 0 ? 1 / x2 : x2;
    }
    // Here x and y are non-zero finite.
    if (ixhi < 0) {
      // Finite x < 0.
      const yint = checkint(iyhi, iylo);
      if (yint === 0) return NaN; // __math_invalid: (x - x) / (x - x) (canonical NaN)
      if (yint === 1) signBias = SIGN_BIAS;
      ixhi &= 0x7fffffff;
      topx &= 0x7ff;
    }
    if (((topy & 0x7ff) - 0x3be) >>> 0 >= 0x43e - 0x3be) {
      // Note: sign_bias == 0 here because y is not odd.
      if (ixhi === 0x3ff00000 && ixlo === 0) return 1.0;
      const ixGt1 = ixhi > 0x3ff00000 || (ixhi === 0x3ff00000 && ixlo !== 0);
      if ((topy & 0x7ff) < 0x3be) {
        // |y| < 2^-65, x^y ~= 1 + y*log(x).
        return ixGt1 ? 1.0 + y : 1.0 - y;
      }
      return ixGt1 === topy < 0x800 ? Infinity : 0.0; // __math_oflow (0) : __math_uflow (0)
    }
    if (topx === 0) {
      // Normalize subnormal x so exponent becomes negative.
      F64[0] = x * P2_52;
      ixhi = I32[HI] & 0x7fffffff;
      ixlo = I32[LO];
      ixhi = (ixhi - (52 << 20)) | 0; // ix -= 52ULL << 52
    }
  }

  const hi = logInline(ixhi, ixlo);
  const lo = logTail;
  // yhi = asdouble (iy & -1ULL << 27)
  I32[HI] = iyhi;
  I32[LO] = iylo & 0xf8000000;
  const yhi = F64[0];
  const ylo = y - yhi;
  // lhi = asdouble (asuint64 (hi) & -1ULL << 27)
  F64[0] = hi;
  I32[LO] = I32[LO] & 0xf8000000;
  const lhi = F64[0];
  const llo = hi - lhi + lo;
  const ehi = yhi * lhi;
  const elo = ylo * lhi + y * llo; // |elo| < |ehi| * 2^-25.
  return expInline(ehi, elo, signBias);
}

/**
 * JS `Math.pow` / `**` semantics (V8 math::pow with --use-std-math-pow),
 * computed with the Arm/glibc algorithm above.
 * Every NaN result is the canonical NaN (0x7ff8000000000000), so even the
 * NaN bit pattern is the same on every platform (hardware default NaNs differ:
 * x64 produces 0xfff8000000000000, arm64 0x7ff8000000000000).
 */
export function pow(x, y) {
  if (Number.isNaN(y)) return NaN;
  if ((y === Infinity || y === -Infinity) && (x === 1 || x === -1)) return NaN;
  // V8 quietens a NaN x; C pow(NaN, y) is 1 for y == +-0 and NaN otherwise
  // (and y == 2 / y == 0.5 below give NaN too).
  if (Number.isNaN(x)) return y === 0 ? 1.0 : NaN;
  if (y === 2) return x * x;
  if (y === 0.5) {
    if (x === Infinity || x === -Infinity) return Infinity;
    if (x < 0) return NaN; // sqrt(negative)
    return Math.sqrt(x + 0);
  }
  return corePow(x, y);
}
