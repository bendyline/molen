#!/usr/bin/env node
// Embed the primers (primers/*.md) in the package as strings and gather them into the shipped
// docs bundle as llms-mini.txt. `--check` fails when either output is stale (pnpm docs:check).
// The primers are hand-written; test/primers.test.ts checks that each names every field and
// value of its schema and that every example in it compiles.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes('--check');
const read = (name) => readFileSync(join(here, 'primers', `${name}.md`), 'utf8');
const primers = { film: read('film'), game: read('game'), scene: read('scene') };

const ts = `// Generated by scripts/build-primers.mjs from primers/*.md. Do not edit by hand.

/** Teaches a model to write a molen/film@1 document (about 600 words). */
export const filmPrimer: string = ${JSON.stringify(primers.film)};

/** Teaches a model to write a molen/game@1 document (about 600 words). */
export const gamePrimer: string = ${JSON.stringify(primers.game)};

/** Teaches a model to write a data-only molen/scene@3 by hand (about 700 words). */
export const scenePrimer: string = ${JSON.stringify(primers.scene)};
`;

const mini = `# Molen for language models: three short primers

Each section below is a complete prompt block, about 600 to 700 words, that teaches a model one
document. A film or a game document is compiled by @bendyline/molen-stage into a data-only
scene; a scene is Molen's own format, written by hand. The same text is exported by
@bendyline/molen-stage as filmPrimer, gamePrimer and scenePrimer.

${primers.film.trim()}

${primers.game.trim()}

${primers.scene.trim()}
`;

const outputs = [
  [join(here, 'src', 'primers.generated.ts'), ts],
  [join(here, '..', '..', 'docs-src', 'llms-mini.txt'), mini],
];
let stale = 0;
for (const [file, text] of outputs) {
  let current = '';
  try {
    current = readFileSync(file, 'utf8');
  } catch {}
  if (current === text) continue;
  if (check) {
    console.error(`stale: ${file} (run node packages/stage/scripts/build-primers.mjs)`);
    stale++;
  } else writeFileSync(file, text);
}
if (stale > 0) process.exit(1);
if (!check) console.log('primers written');
